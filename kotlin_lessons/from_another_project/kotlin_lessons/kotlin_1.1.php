<h4>Написание кода программы</h4>
<p>Теперь определим на жестком диске каталог для файлов с исходным кодом. Например, в моем случае каталог будет находиться по пути <span class="b">c:/kotlin</span>. 
В этом каталоге создадим новый файл, который назовем <span class="b">app.kt</span>. Расширение <span class="b">kt</span> - это расширение файлов на языке Kotlin.</p>
<p>Далее определим в этом файле код, который будет выводить некоторое сообщение на консоль:</p>
<pre class="brush:kt;">
fun main(){
    println("Hello METANIT.COM")
}
</pre>
<p>Точкой входа в программу на Kotlin является функция <span class="b">main</span>. Для определения функции применяется ключевое слово <span class="b">fun</span>, 
после которого идет название функции - то есть <span class="b">main</span>. Данная функция не принимает никаких параметров, поэтому после названия функции указываются пустые скобки.</p>
<p>Далее в фигурных скобках определяются собственно те действия, которые выполняет функция main. 
В данном случае внутри функции main выполняется другая функция - <span class="b">println()</span>, которая выводит некоторое сообщение на консоль.</p>
<img src="./pics/1.11.png" alt="Первая программа на Kotlin в текстовом редакторе" style="width:400px;" />
<p>Откроем командную строку. Вначале с помощью команды <span class="b">cd</span> перейдем к папке, где находится файл <span class="b">app.kt</span>. 
Затем для компиляции программы введем следующую команду:</p>
<pre class="sh">
c:\kotlinc\bin\kotlinc app.kt 
</pre>
<p>В данном случае мы передаем компилятору <span class="b">c:\kotlin\bin\kotlinc</span> для компиляции файл app.kt. (Чтобы не писать полный путь к компилятору, 
путь к нему можно добавить в переменную PATH в переменных среды). В результате в папке с исходным кодом появится файл <span class="b">AppKt.class</span> - это скомпилированный код в виде байт-кода для виртуальной машины Java.</p>
<p>Теперь запустим приложение с помощью второй утилиты - <b>kotlin</b>:</p> 
<pre class="sh">
c:\kotlinc\bin\kotlin AppKt 
</pre>
<p>И консоль должна нам вывести сообщение "Hello METANIT.COM". Полный вывод:</p>
<pre class="sh">
C:\Windows\system32&gt;cd c:\kotlin
c:\kotlin&gt;c:\kotlinc\bin\kotlinc app.kt 
c:\kotlin&gt;c:\kotlinc\bin\kotlin AppKt 
Hello METANIT.COM

c:\kotlin&gt;
</pre>
	

