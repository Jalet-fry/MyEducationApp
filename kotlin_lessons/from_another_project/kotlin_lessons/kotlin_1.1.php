	<p><span class="b">Kotlin</span> представляет современный, статически типизированный и один из самых быстроразвивающихся языков 
программирования, созданный и развиваемый компанией JetBrains. 
Kotlin можно использовать для создания самых разных приложений. Это и приложения для мобильных устройств - Android, iOS. Причем Kotlin позволяет писать кроссплатформенный 
код, который будет применяться на всех платформах. Это и веб-приложения, причем как серверные приложения, которые отрабатывают на стороне на стороне сервера - бекэнда, 
так и браузерные клиентские приложения - фронтенд. Kotlin также можно применять для создания десктопных приложений, для Data Science и так далее.</p>
<p>Таким образом, круг платформ, для которых можно создавать приложения на Kotlin, чрезвычайно широк - Windows, Linux, Mac OS, iOS, Android.</p>

<p>Самым популярным направлением, где применяется Kotlin, является прежде всего разработка под ОС Android. Причем настолько популярным, 
что компания Google на конференции Google I/O 2017 провозгласила Kotlin одним из официальных языков для разработки под Android (наряду с 
Java и C++), а инструменты по работе с данным языком были по умолчанию включены в функционал среды разработки Android Studio начиная с версии 3.0.</p>
<p>Официальный сайт языка - <a href="https://kotlinlang.org/" rel="nofollow">https://kotlinlang.org/</a>, где можно найти самую последнюю и самую подробную информацию по языку.</p>
<p>Первая версия языка вышла 15 февраля 2016 года. Хотя сама разработка языка велась с 2010 года. Текущей версией языка на данный момент 
является версия 2.1, которая вышла в ноябре 2024 годf.</p>
<p>Свое название язык Kotlin получил от названия острова, который расположен близ города Санкт-Петербург, в котором в.</p>
<p>Kotlin испытал влияние многих языков: Java, Scala, Groovy, C#, JavaScript, Swift и позволяет писать программы как в объектно-ориентированном, так и в функциональном стиле. 
Он имеет ясный и понятный синтаксис и довольно легок для обучения.</p>
<p>Но Kotlin - это не просто очередной язык программирования. На сегодняшний день это целая экосистема:</p>
<img src="./pics/1.0.png" alt="Экосистема языка Kotlin" />
<p>Ядро этой экосистемы - <span class="b">Common Kotlin</span>, которое включает в себя собственно язык, основные библиотеки и базовые инструменты для построения программ.</p>
<p>Для взаимодействия с конкретной платформой имеются предназначенные для этой платформы версия Kotlin: <span class="b">Kotlin/JVM</span>, 
<span class="b">Kotlin/JS</span> и <span class="b">Kotlin/Native</span>. Эти специфические версии представляют расширения для языка Kotlin, 
а также специфичные для конкретной платформы бибилиотеки и инструменты разработки.</p>
<p>Также стоит отметить, что Kotin развивается как opensource, исходный код проекта можно посмотреть в репозитории на github по адресу 
<a href="https://github.com/JetBrains/kotlin/" rel="nofollow">https://github.com/JetBrains/kotlin/</a>.</p>
<p>Перед началом работы с Kotlin следует отметить, что нам потребуется JDK (Java Development Kit). Про установку Java можно прочитать на данном сайте https://metanit.com в статье <a href="https://metanit.com/java/tutorial/1.6.php">Установка Java</a>. Однако знать сам язык программирования Java необязательно. 
Достаточно лишь знать, что в общем случае Kotlin работает поверх виртуальной машины Java (JVM). Благодаря этому Kotlin может использовать 
библиотеки, написанные на Java. Аналогично из программы на Java можно запускать код Kotlin. Однако Kotlin/Native позволяет писать приложения, которые компилируются в нативный код и которые 
выполняются без JVM.</p>
<p>Также стоит отметить, что так как одно из самых популярных направлений разработки на Kotlin представляет разработка под Android, то на этом сайте https://metanit.com также имеется 
<a href="https://metanit.com/kotlin/jetpack">руководство по созданию мобильных приложений</a> на Kotlin</p>

<h3>Первая программа на Kotlin</h3>
<p>Создадим первую программу на языке Kotlin. В дальнейшем при работе с Kotlin мы будем использовать специальную программу - среду разработки <b>Intellij IDEA</b>, которая во многом облегчает 
написание приложений на Kotlin. Однако эта среда довольно тяжеловесна, и в реальности для создания приложений нам нужно всего два компонента - текстовый редактор для набора кода программы и 
компилятор для компиляции кода в приложение.</p>
<p>В качестве текстового редактора можно взять любой понравившийся. Например, я буду ориентироватья на Visual Studio Code.</p>
<p>Загрузить компилятор непосредственно для самого языка Kotlin можно по адресу <a href="https://github.com/JetBrains/kotlin/releases/latest/" rel="nofollow">https://github.com/JetBrains/kotlin/releases/latest/</a>. 
В самом низу страницы под заголовком <span class="b">Assets</span> мы можем найти общую версию компилятора, версии компилятора Kotlin/Native для разных операционных систем, а также исходный код. Нас интересует общая версия компилятора, которая называется по шаблону 
<code>kotlin-compiler-x.x.x.zip</code>, где <code>x.x.x</code> - это номер версии. Например, в моем случае это файл <span class="b">kotlin-compiler-2.1.0.zip</span>:</p>
<img src="./pics/1.9.png" alt="Компилятор Kotlin" style="width:700px;" />
<p>Загрузим и распакуем из архива папку <span class="b">kotlinc</span>. В распакованном архиве в папке bin мы можем найти утилиту <span class="b">kotlinc</span> - этои есть компилятор Kotlin. 
Кроме того, здесь также располагается приложение <b>kotlin</b>, которое выполняет скомпилированный код:</p>
<img src="./pics/1.10.png" alt="Компилятор для языка Kotlin" />
<p>Стоит отметить, что на Linux, например, на Ubuntu, Kotlin можно установить через пакетный менеджер snap с помощью команды</p>
<pre class="sh">sudo snap install kotlin --classic</pre>

