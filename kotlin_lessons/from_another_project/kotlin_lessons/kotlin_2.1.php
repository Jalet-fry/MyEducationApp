	<p>Для хранения данных в программе в Kotlin, как и в других языках программирования, применяются переменные. 
<span class="b">Переменная</span> представляет именованный участок памяти, который хранит некоторое значение.</p>
<p>Каждая переменная характеризуется определенным именем, типом данных и значением. Имя переменной представляет поизвольный идентификатор, который может содержать алфавитно-цифровые символы или символ подчеркивания и 
должен начинаться либо с алфавитного символа, либо со знака подчеркивания. Для определения переменной можно использовать либо ключевое слово 
<span class="b">val</span>, либо ключевое слово <span class="b">var</span>.</p>
<p>Формальное определение переменной:</p>
<pre class="brush:kt;">
val|var имя_переменной: тип_переменной
</pre>
<p>Вначале идет слово <span class="b">val</span> или <span class="b">var</span>, затем имя переменной и через двоеточие тип переменной.</p>
<p>Например, определим переменную age:</p>
<pre class="brush:kt;">
var age: Int
</pre>
<p>То есть в данном случае объявлена переменная age, которая имеет тип <span class="b">Int</span>. Тип Int говорит о том, что переменная будет содержать целочисленные значения.</p>
<p>После определения переменной ей можно присвоить значение:</p>
<pre class="brush:kt;">
fun main() {
    var age: Int
    age = 23
    println(age)
}
</pre>
<p>Для присвоения значения переменной используется знак равно. Затем мы можем производить с переменной различные операции. Например, в данном 
случае с помощью функции <code>println()</code> значение переменной выводится на консоль. И при запуске этой программы на консоль будет выведено число 23.</p>
<p>Присвоение значения переменной должно производиться только после ее объявления. И также мы можем сразу присвоить переменной начальное значение при ее объявлении. 
Такой прием называется инициализацией:</p>
<pre class="brush:kt;">
fun main() {
    var age: Int = 23
    println(age)
}
</pre>
<p>Однако обязательно надо присвоить переменной некоторое значение до ее использования:</p>
<pre class="brush:kt;">
fun main() {

    var age: Int
    println(age)// Ошибка, переменная не инициализирована
}
</pre>
<h3>Изменяемые и неизменяемые переменные</h3>
<p>Выше было сказано, что переменные могут объявляться как с помощью слова <span class="b">val</span>, так и с помощью слова <span class="b">var</span>. 
В чем же разница между двумя этими способами?</p>
<p>С помощью ключевого слова <span class="b">val</span> определяется неизменяемая переменная (immutable variable) или <span class="b">переменная только для чтения</span> (read-only). 
То есть мы можем присвоить значение такой переменной только один раз, но изменить его после первого присвоения мы уже не сможем. Например, в следующем случае мы получим ошибку:</p>
<pre class="brush:kt;">
fun main() {
    val age: Int
    age = 23        // здесь норм - первое присвоение
    age = 56        // здесь ошибка - переопределить значение переменной нельзя
    println(age)
}
</pre>
<p>А у переменной, которая определена с помощью ключевого слова <span class="b">var</span> мы можем многократно менять значения (mutable variable):</p>
<pre class="brush:kt;">
fun main() {
    var age: Int
    age = 23
    println(age)
    age = 56
    println(age)
}
</pre>
<p>Поэтому если не планируется изменять значение переменной в программе, то лучше определять ее с ключевым словом <span class="b">val</span>.</p>

