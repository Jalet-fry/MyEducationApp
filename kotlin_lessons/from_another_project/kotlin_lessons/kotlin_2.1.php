<h3>Определение констант</h3>
<p>Также Kotlin поддерживает константы времени компиляции. Для их определения применяются ключевые слова <span class="b">const val</span>:</p>
<pre class="brush:kt;">
const val maxAge = 120  // константа
fun main() {
    println(maxAge)
}
</pre>
<p>В данном случае <code>maxAge</code> является константой.</p>
<p>Отличительной особенностью констант является то, что они на стадии <span class="b">компиляции</span> должны иметь некоторое значение, и это значение изменить нельзя. Это 
накладывает на использование констант ряд ограничений:</p>
<ul>
<li><p>Естественно нельзя изменить значение константы:</p>
<pre class="brush:kt;">
const val maxAge = 120  // константа
fun main() {
    maxAge = 1500   // ошибка 
    println(maxAge)
}
</pre>
<p>Здесь при попытке присвоения константе maxAge нового значения в функции main мы столкнемся с ошибкой на стадии компиляции. Если мы работаем в среде Intellij IDEA или Android Studio, 
то уже при написании кода на подобные ошибки укажет сама среда разработки.</p>
</li>

<li><p>Константа должна объявляться на самом верхнем уровне (вне класса/функции):</p>
<pre class="brush:kt;">
fun main() {
    const val maxAge = 120   // ошибка 
    println(maxAge)
}
</pre></li>

<li><p>Тип данных константы должен соответствовать одному из примитивных (например, Int) или типу String</p></li>
</ul>

<p>Также стоит отметит отличие <span class="b">val</span>-переменных от констант (<span class="b">const val</span>): значение <span class="b"></span>val</span>-переменных 
устанавливается во время выполнения, а значение констант - во время компиляции. Значение <span class="b">val</span>-переменной также нельзя изменить после установки, однако мы можем объявить <span class="b">val</span>-переменную, а потом дальше в программе присвоить ей значение. Константе 
же необходимо присвоить значение сразу при определении.</p>

	

