<h3>Состояние DrawerState</h3>
<p>Выдвижная панель может быть открыта или закрыта. Соответственно компонент может находиться в двух состояниях. Для хранения состояния применяется класс <span class="b">DrawerState</span>. Внутри этого класса для 
хранения состояния применяется перечисление <span class="b">DrawerValue</span>. В частности, оно имеет два значения: 
<code>DrawerValue.Closed</code> (панель закрыта) и <code>DrawerValue.Open</code> (панель открыта).</p>
<p>Для создания и управления состояния DrawerState применяется функция <span class="b">rememberDrawerState()</span>:</p>
<pre class="brush:kt;">
@Composable
fun rememberDrawerState(
    initialValue: DrawerValue,
    confirmStateChange: (DrawerValue) -&gt; Boolean = { true }
): DrawerState
</pre>
<p>В качестве обязательного параметра она принимает значение DrawerValue, которое указывает, открыта или закрыта панель по умолчанию. Для получения информации о состоянии DrawerState предоставляет 
ряд свойств:</p>
<ul>
<li><p><span class="b">currentValue</span>: текущее состояние в виде значения DrawerValue</p></li>
<li><p><span class="b">isClosed</span>: если равно true, то выдвижная панель скрыта</p></li>
<li><p><span class="b">isOpen</span>: если равно true, то выдвижная панель раскрыта</p></li>
</ul>

