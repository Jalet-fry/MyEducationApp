<p>Как видно, ModalDrawerSheet имеет некоторую стандартную стилизацию и упрощает создание содержимого. И мы можем помещать в ModalDrawerSheet любые компоненты, как в данном случае 
компоненты TextButton. Тем не менее для определения элементов в ModalDrawerSheet в Jetpack Compose предназначен специальный компонент - <span class="b">NavigationDrawerItem</span>:</p>
<pre class="brush:kt;">
@Composable
fun NavigationDrawerItem(
    label: @Composable () -&gt; Unit,
    selected: Boolean,
    onClick: () -&gt; Unit,
    modifier: Modifier = Modifier,
    icon: (@Composable () -&gt; Unit)? = null,
    badge: (@Composable () -&gt; Unit)? = null,
    shape: Shape = NavigationDrawerTokens.ActiveIndicatorShape.value,
    colors: NavigationDrawerItemColors = NavigationDrawerItemDefaults.colors(),
    interactionSource: MutableInteractionSource? = null
): Unit
</pre>
<p>Отмечу основные параметры компонента:</p>
<ul>
<li><p><code>label</code>: определяет содержимое</p></li>
<li><p><code>selected</code>: указывает, будет ли выделен элемент (при значении true)</p></li>
<li><p><code>onClick</code>: обработчик нажатия на компонент</p></li>
<li><p><code>colors</code>: устанавливает цвета. Для установки цветов можно использовать функцию <code>NavigationDrawerItemDefaults.colors()</code></p>
<pre class="brush:kt;">
@Composable
fun colors(
    selectedContainerColor: Color = NavigationDrawerTokens.ActiveIndicatorColor.value,
    unselectedContainerColor: Color = Color.Transparent,
    selectedIconColor: Color = NavigationDrawerTokens.ActiveIconColor.value,
    unselectedIconColor: Color = NavigationDrawerTokens.InactiveIconColor.value,
    selectedTextColor: Color = NavigationDrawerTokens.ActiveLabelTextColor.value,
    unselectedTextColor: Color = NavigationDrawerTokens.InactiveLabelTextColor.value,
    selectedBadgeColor: Color = selectedTextColor,
    unselectedBadgeColor: Color = unselectedTextColor
): NavigationDrawerItemColors
</pre>
<p>Она устанавливает следующие цвета:</p>
<ul>
<li><p><code>selectedContainerColor</code>: цвет фона выбранного элемента</p></li>
<li><p><code>unselectedContainerColor</code>:  цвет фона невыбранного элемента</p></li>
<li><p><code>selectedIconColor</code>:  цвет иконки выбранного элемента</p></li>
<li><p><code>unselectedIconColor</code>: цвет иконки невыбранного элемента</p></li>
<li><p><code>selectedTextColor</code>:  цвет текста выбранного элемента</p></li>
<li><p><code>unselectedTextColor</code>: цвет текста невыбранного элемента</p></li>
<li><p><code>selectedBadgeColor</code>: цвет значка выбранного элемента</p></li>
<li><p><code>unselectedBadgeColor</code>: цвет значка невыбранного элемента</p></li>
</ul>
</li>
</ul>
