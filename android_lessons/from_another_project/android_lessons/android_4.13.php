<p>Компонент <span class="b">ModalNavigationDrawer</span> предназначен для создания приложений с выдвижной панелью, где часто располагается какое-нибдуь меню. Этот компонент имеет следующее определение:</p>
<pre class="brush:kt;">
@Composable
fun ModalNavigationDrawer(
    drawerContent: @Composable () -&gt; Unit,
    modifier: Modifier = Modifier,
    drawerState: DrawerState = rememberDrawerState(DrawerValue.Closed),
    gesturesEnabled: Boolean = true,
    scrimColor: Color = DrawerDefaults.scrimColor,
    content: @Composable () -&gt; Unit
): Unit
</pre>
<p>Параметры компонента:</p>
<ul>
<li><p><code>drawerContent</code>: содержимое выдвижной панели</p></li>
<li><p><code>modifier</code>: применяемыек компоненты модификаторы</p></li>
<li><p><code>drawerState</code>: состояние в виде объекта <span class="b">DrawerState</span>.  Для определения состояния применяется функция <code>rememberDrawerState()</code>, в которую передается 
передается начальное состояние панели с помощью констант перечисления <span class="b">DrawerValue</span>: <code>DrawerValue.Closed</code> (панель закрыта) и <code>DrawerValue.Open</code> (панель открыта)
По умолчанию равно <code>rememberDrawerState(DrawerValue.Closed)</code></p></li>
<li><p><code>gesturesEnabled</code>: указывает, может или нет панель управляться касаниями. По умолчанию равно <code>true</code></p></li>
<li><p><code>scrimColor</code>: цвет, который скрывает основное содержимое приложения, когда панель открыта</p></li>
<li><p><code>content</code>: остальное содержимое приложения</p></li>
</ul>
<p>Первый и последний параметр являются обязательными и в реальности они могут представлять любые компоненты. Например, определим простейшую выдвижную панель:</p>
<pre class="brush:kt;">
package com.example.helloapp

import android.os.Bundle
import androidx.activity.ComponentActivity
import androidx.activity.compose.setContent
import androidx.compose.material3.Text
import androidx.compose.material3.ModalNavigationDrawer
import androidx.compose.ui.graphics.Color
import androidx.compose.ui.unit.sp

class MainActivity : ComponentActivity() {
    override fun onCreate(savedInstanceState: Bundle?) {
        super.onCreate(savedInstanceState)
        setContent {
            ModalNavigationDrawer(
                drawerContent = { Text("Drawer", fontSize = 22.sp, color=Color.LightGray)  },
                scrimColor = Color.DarkGray,
                content={Text("Main Content", fontSize = 28.sp)})
        }
    }
}
</pre>
<p>Здесь и содержимое выдвижной панели, и содержимое основной части приложения представлено компонентом Text. При выдвижении панели основной контент закрашивается сервым цветом - то есть фактически это цвет самой панели. 
В данном случае по умолчанию панель не видна, и для ее выдвижения надо провести пальцем от левой стороны приложения вправо:</p>
