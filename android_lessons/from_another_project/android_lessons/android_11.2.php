<p>Чтобы обеспечить определенный уровень единообразия дизайна между различными приложениями с точки зрения выбора цвета, типографики, формы и других параметров пользовательского интерфейса 
компания Google разработала набор рекоммендаций, который называется <span class="b">Material Design</span>. 
Помимо рекомендаций по проектированию, Material Design также включает набор компонентов пользовательского интерфейса и тем, которые можно использовать при разработке макетов пользовательского 
интерфейса.</p>
<p>Стоит отметить, что сам Material Design постоянно развивается. Так, на момент написания текущей статьи в Android Studio (в частности, в версии Android Studio Iguana) по умолчанию используется 
Material Design 3. Material Design 3 обеспечивает основу для Material You — функциональности, представленной в Android 12, которая позволяет приложению применять 
настройки, установленные пользователем на устройстве.</p>
<p>При создании проекта по умолчанию в Android Studio, например, по умолчанию в проект добавляется каталог <span class="b">ui.theme</span>, который содержит ряд файлов:</p>
<img src="./pics/19.1.png" alt="Темы в Jetpack Compose на Kotlin в Android Studio" />
<p>Сама тема объявляется в файле <span class="b">Theme.kt</span>, который начинается с объявления различных цветовых палитр для использования, когда устройство находится в светлом (дневном) или 
темном (ночном) режиме. Эти палитры создаются путем вызова функций <code>darkColorScheme()</code> и <code>lightColorScheme()</code>. Параметры этих функций представляют цветовые слоты, которые задают цвета 
для различных ситуаций:</p>
<pre class="brush:kt;">
private val DarkColorScheme = darkColorScheme(
        primary = Purple80,
        secondary = PurpleGrey80,
        tertiary = Pink80
)

private val LightColorScheme = lightColorScheme(
        primary = Purple40,
        secondary = PurpleGrey40,
        tertiary = Pink40

        /* Other default colors to override
    background = Color(0xFFFFFBFE),
    surface = Color(0xFFFFFBFE),
    onPrimary = Color.White,
    onSecondary = Color.White,
    onTertiary = Color.White,
    onBackground = Color(0xFF1C1B1F),
    onSurface = Color(0xFF1C1B1F),
    */
)
</pre>
