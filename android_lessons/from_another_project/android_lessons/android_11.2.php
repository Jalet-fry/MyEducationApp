        fontWeight = FontWeight.Medium,
        fontSize = 11.sp,
        lineHeight = 16.sp,
        letterSpacing = 0.5.sp
    )
    */
)
</pre>
<h3>Создание темы</h3>
<p>Создание собственной темы включает в себя редактирование этих файлов с использованием различных цветов, типографики и настроек формы. Эти изменения затем будут использоваться 
компонентами Material, которые составляют пользовательский интерфейс приложения.</p>
<p>Для создания темы в графическом режиме можно использовать такой инструмент как <span class="b">Material Theme Builder</span>, который предоставляется компанией Google и который доступен по адресу 
<a href="https://m3.material.io/theme-builder#/custom" rel="nofollow">https://m3.material.io/theme-builder#/custom</a>:</p>
<img src="./pics/19.2.png" alt="Создание темы в Jetpack Compose на Kotlin в Android Studio" />
<p>На этой странице надо нажать в верхней части экрана на кнопку "Custom". Затем в разделе "Core colors" можно нажать на кружок цвета и установить любой цвет</p>
<p>Когда тема будет готова, нажмите кнопку "Export" в правом верхнем углу и выбрать опцию «Jetpack Compose (Theme.kt)». При появлении запроса сохраните файл в подходящем месте файловой 
системы вашего компьютера. Тема будет сохранена в виде архива с именем "material-theme.zip".</p>
<img src="./pics/19.3.png" alt="Загрузка темы в Jetpack Compose на Kotlin в Android Studio" />
<p>Распакуем загруженный файл и в папке "material-theme/ui/theme" мы сможем найти два файла:</p>
<ul>
<li><p>Color.kt</p></li>
<li><p>Theme.kt</p></li>
</ul>
<p>Для добавления этих файлрв проект сначала нужно удалить файлы старой темы - файлы <span class="b">Color.kt</span> и <span class="b">Theme.kt</span> из папки <code>ui.theme</code> 
проекта Android Studio. После удаления файлов возьмем файлы пользовательских тем из распакованной папки "material-theme/ui/theme" и скопируум их в папку <code>ui.theme</code>  проекта. 
После добавления файлов может потребоваться отредактировать новые файлы, чтобы объявление пакета в этих файлах соответствовало текущему проекту.</p>

	

