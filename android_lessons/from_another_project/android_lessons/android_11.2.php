<p>Темы Material Design 3 также могут включать поддержку динамических цветов посредством вызовов функций <span class="b">dynamicDarkColorScheme()</span> и <span class="b">dynamicLightColorScheme()</span>, 
передавая текущий локальный контекст в качестве параметра. Эти функции затем сгенерируют цветовые схемы, соответствующие настройкам пользователя на устройстве. 
Поскольку динамические цвета поддерживаются только начиная с Android 12 (S), то для более ранних версий Android определяются резервные цветовые темы:</p>
<pre class="brush:kt;">
@Composable
fun HelloAppTheme(
        darkTheme: Boolean = isSystemInDarkTheme(),
        // динамические цвета доступны только на Android 12+
        dynamicColor: Boolean = true,
        content: @Composable () -&gt; Unit
) {
    val colorScheme = when {
        dynamicColor && Build.VERSION.SDK_INT &gt;= Build.VERSION_CODES.S -&gt; {
            val context = LocalContext.current
            if (darkTheme) dynamicDarkColorScheme(context) else dynamicLightColorScheme(context)
        }
        // резервные цветые темы, если Android 11 и ниже
        darkTheme -&gt; DarkColorScheme
        else -&gt; LightColorScheme
    }
    val view = LocalView.current
    if (!view.isInEditMode) {
        SideEffect {
            val window = (view.context as Activity).window
            window.statusBarColor = colorScheme.primary.toArgb()
            WindowCompat.getInsetsController(window, view).isAppearanceLightStatusBars = darkTheme
        }
    }

    MaterialTheme(
            colorScheme = colorScheme,
            typography = Typography,
            content = content
    )
}
</pre>
<p>Обратите внимание, что динамические цвета будут работать только в том случае, если они включены на устройстве пользователем в настройках в разделе обоев и стилей приложения.</p>
<p>Также по умолчанию проект имеет настройки типографики - в файле <span class="b">Type.kt</span>. В частности, Material Design имеет набор масштабов шрифта (два из них закомментированы):</p>
<pre class="brush:kt;">
// Настройки типографики Material
val Typography = Typography(
        bodyLarge = TextStyle(
                fontFamily = FontFamily.Default,
                fontWeight = FontWeight.Normal,
                fontSize = 16.sp,
                lineHeight = 24.sp,
                letterSpacing = 0.5.sp
