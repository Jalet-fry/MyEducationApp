<h3>Форма кнопки</h3>
<p>Как видно из предыдущих скриншотов, по умолчанию кнопка имеет округлую форму. Но с помощью параметра <span class="b">shape</span> можно задать любую другую форму, 
которая представляет объект интерфейса <span class="b">Shape</span>. Например, для создания прямоугольной формы можно использовать встроенный объект <span class="b">RectangleShape</span>. 
Для создания кнопки с закругленными углами можно использовать встроенный класс <span class="b">RoundedCornerShape</span>, в конструктор которого передается радиус закругления:</p>
<pre class="brush:kt;">
package com.example.helloapp

import android.os.Bundle
import androidx.activity.ComponentActivity
import androidx.activity.compose.setContent
import androidx.compose.foundation.layout.Column
import androidx.compose.foundation.layout.padding
import androidx.compose.foundation.shape.RoundedCornerShape
import androidx.compose.material3.Button
import androidx.compose.ui.unit.sp
import androidx.compose.material3.Text
import androidx.compose.ui.Modifier
import androidx.compose.ui.graphics.RectangleShape
import androidx.compose.ui.unit.dp

class MainActivity : ComponentActivity() {
    override fun onCreate(savedInstanceState: Bundle?) {
        super.onCreate(savedInstanceState)
        setContent {
            Column{
                Button(onClick = {},
                    shape = RectangleShape,     // прямоугольная кнопка
                    modifier = Modifier.padding(10.dp)
                ){ Text("Button 1", fontSize = 28.sp) }

                Button(onClick = {},
                    shape = RoundedCornerShape(15.dp),  // округлая кнопка
                    modifier = Modifier.padding(10.dp)
                ){ Text("Button 2", fontSize = 28.sp) }
            }
        }
    }
}
</pre>
