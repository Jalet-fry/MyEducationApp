<h3>Файл Gradle модуля</h3>
<p>Проект приложения может состоять из одного или нескольких модулей. И для каждого модуля потребуется собственный файл сборки Gradle. По умолчанию, когда создается проект в Android Studio, в нем создается 
один модулья, который называется <span class="b">app</span>. Соответственно для него определяется файл сборки Gradle уровня модуля, который называется <span class="b">build.gradle.kts</span> 
<span class="ii">(Module :app)</span>:</p>
<img src="./pics/20.3.png" alt="Файл build.gradle.kts модуля в Android Studio" />
<p>По умолчанию он выглядит примерно следующим образом:</p>
<pre class="brush:py;">
plugins {
    alias(libs.plugins.androidApplication)
    alias(libs.plugins.jetbrainsKotlinAndroid)
}

android {
    namespace = "com.example.helloapp"
    compileSdk = 34

    defaultConfig {
        applicationId = "com.example.helloapp"
        minSdk = 24
        targetSdk = 34
        versionCode = 1
        versionName = "1.0"

        testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
        vectorDrawables {
            useSupportLibrary = true
        }
    }

    buildTypes {
        release {
            isMinifyEnabled = false
            proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
        }
    }
    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_1_8
        targetCompatibility = JavaVersion.VERSION_1_8
    }
    kotlinOptions {
        jvmTarget = "1.8"
    }
    buildFeatures {
        compose = true
    }
    composeOptions {
        kotlinCompilerExtensionVersion = "1.5.1"
    }
    packaging {
        resources {
            excludes += "/META-INF/{AL2.0,LGPL2.1}"
        }
    }
}

dependencies {

    implementation(libs.androidx.core.ktx)
    implementation(libs.androidx.lifecycle.runtime.ktx)
    implementation(libs.androidx.activity.compose)
    implementation(platform(libs.androidx.compose.bom))
    implementation(libs.androidx.ui)
    implementation(libs.androidx.ui.graphics)
    implementation(libs.androidx.ui.tooling.preview)
    implementation(libs.androidx.material3)
    testImplementation(libs.junit)
    androidTestImplementation(libs.androidx.junit)
    androidTestImplementation(libs.androidx.espresso.core)
    androidTestImplementation(platform(libs.androidx.compose.bom))
    androidTestImplementation(libs.androidx.ui.test.junit4)
    debugImplementation(libs.androidx.ui.tooling)
    debugImplementation(libs.androidx.ui.test.manifest)
}
</pre>
<p>Как правило, если требуется внести некоторые изменения в конфигурацию сборки модуля, то именно то место, где подобные изменения производятся. Вкратце рассмотрим основные секции файла.</p>
<p>Файл сборки начинается с объявления плагинов приложения Android и Kotlin:</p>
<pre class="brush:kt;">
plugins {
    alias(libs.plugins.androidApplication)
    alias(libs.plugins.jetbrainsKotlinAndroid)
}
</pre>
<p>Далее идет раздел <code>android</code>, который начинается с объявляения пространствоа имен проекта и версии SDK, которая будет использоваться при сборке модуля:</p>
<pre class="brush:kt;">
android {
    namespace = "com.example.helloapp"
    compileSdk = 34
</pre>
<p>Элементы, объявленные в подразделе <code>defaultConfig</code>, определяют элементы, которые будут созданы в файле <code>AndroidManifest.xml</code> модуля во время сборки:</p>
<pre class="brush:py;">
defaultConfig {
    applicationId = "com.example.helloapp"
    minSdk = 24
    targetSdk = 34
    versionCode = 1
    versionName = "1.0"

    testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
    vectorDrawables {
        useSupportLibrary = true
    }
}
</pre>
<p>Подраздел <span class="b">buildTypes</span> указывает, следует ли и как запускать ProGuard в APK-файле при сборке релизной версии приложения:</p>
<pre class="brush:py;">
buildTypes {
    release {
        isMinifyEnabled = false
        proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
    }
}
</pre>
<p>В текущей конфигурации ProGuard не будет запускаться при сборке модуля. Чтобы включить ProGuard, запись <code>minifyEnabled</code> должна быть изменена с <code>false</code> на <code>true</code>. 
А выражение <code>proguardFiles()</code> определяет применяемые файлы ProGuard. Файл <span class="b">proguard-rules.pro</span> можно найти в каталоге модулей проекта. Изменения, внесенные в этот файл, переопределяют настройки по умолчанию в файле 
<span class="b">proguard-android.txt</span>, который находится в каталоге установки Android SDK в папке "sdk/tools/proguard".</p>
<p>Поскольку в данном случае подраздел <span class="b">buildTypes</span> не определяет конфигурацию для сборки в режиме отладки (режим <code>debug</code>), то при отладке 
будут использоваться значения по умолчанию (созданные без ProGuard, подписанные ключом отладки и включенными символами отладки).</p>
<p>Далее идет подразделы <span class="b">compileOptions</span> и <span class="b">kotlinOptions</span> которые определяют используемую при сборке проекта версию компилятора Java:</p>
<pre class="brush:py;">
compileOptions {
    sourceCompatibility = JavaVersion.VERSION_1_8
    targetCompatibility = JavaVersion.VERSION_1_8
}
kotlinOptions {
    jvmTarget = "1.8"
}
</pre>
<p>И в самом конце идет секция <span class="b">dependencies</span> перечисляет все локальные и удаленные зависимости, от которых зависит модуль. 
Строки зависимостей в приведенном выше файле примера обозначают библиотеки Android, которые необходимо включить из репозитория Android:</p>
<pre class="brush:py;">
dependencies {

    implementation(libs.androidx.core.ktx)
    implementation(libs.androidx.lifecycle.runtime.ktx)
    implementation(libs.androidx.activity.compose)
    implementation(platform(libs.androidx.compose.bom))
    implementation(libs.androidx.ui)
    implementation(libs.androidx.ui.graphics)
    implementation(libs.androidx.ui.tooling.preview)
