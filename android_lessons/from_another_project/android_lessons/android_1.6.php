<h3>Каталог версий libs.versions.toml</h3>
<p>Когда Gradle собирает проект, ему необходимо знать, какие библиотеки необходимы для завершения сборки и соответствующие номера их версий. 
И каталог версий - файле <span class="b">libs.versions.toml</span> позволяет указать, какие версии каких библиотек будут использоваться в проекте. Этот файл имеет содержимое наподобие следующего:</p>
<pre class="brush:kt;">
[versions]
agp = "8.3.0"
kotlin = "1.9.0"
coreKtx = "1.10.1"
junit = "4.13.2"
junitVersion = "1.1.5"
espressoCore = "3.5.1"
lifecycleRuntimeKtx = "2.6.1"
activityCompose = "1.7.0"
composeBom = "2023.08.00"

[libraries]
androidx-core-ktx = { group = "androidx.core", name = "core-ktx", version.ref = "coreKtx" }
junit = { group = "junit", name = "junit", version.ref = "junit" }
androidx-junit = { group = "androidx.test.ext", name = "junit", version.ref = "junitVersion" }
androidx-espresso-core = { group = "androidx.test.espresso", name = "espresso-core", version.ref = "espressoCore" }
androidx-lifecycle-runtime-ktx = { group = "androidx.lifecycle", name = "lifecycle-runtime-ktx", version.ref = "lifecycleRuntimeKtx" }
androidx-activity-compose = { group = "androidx.activity", name = "activity-compose", version.ref = "activityCompose" }
androidx-compose-bom = { group = "androidx.compose", name = "compose-bom", version.ref = "composeBom" }
androidx-ui = { group = "androidx.compose.ui", name = "ui" }
androidx-ui-graphics = { group = "androidx.compose.ui", name = "ui-graphics" }
androidx-ui-tooling = { group = "androidx.compose.ui", name = "ui-tooling" }
androidx-ui-tooling-preview = { group = "androidx.compose.ui", name = "ui-tooling-preview" }
androidx-ui-test-manifest = { group = "androidx.compose.ui", name = "ui-test-manifest" }
androidx-ui-test-junit4 = { group = "androidx.compose.ui", name = "ui-test-junit4" }
androidx-material3 = { group = "androidx.compose.material3", name = "material3" }

[plugins]
androidApplication = { id = "com.android.application", version.ref = "agp" }
jetbrainsKotlinAndroid = { id = "org.jetbrains.kotlin.android", version.ref = "kotlin" }
</pre>
<p>Данный файл подразделен на три секции: <span class="b">[versions]</span>, <span class="b">[libraries]</span> <span class="b">[plugins]</span>. 
Чтобы понять, как работает каталог, в качестве примера рассмотрим подключение библиотеки "androidx-core-ktx". Итак, в секции <span class="b">[libraries]</span> библиотека "androidx-core-ktx" 
объявлена следующим образом:</p>
<pre class="brush:py;">androidx-core-ktx = { group = "androidx.core", name = "core-ktx", version.ref = "coreKtx" }</pre>
<p>Параметр <code>versions.ref</code> 
указывает, как на библиотеку будут ссылаться в секции <span class="b">[versions]</span> - через имя "coreKtx".</p>
<p>В секции <span class="b">[versions]</span> мы можем увидеть, что для этой библиотеки указана версия 1.10.1:</p>
<pre class="brush:py;">
[versions]
coreKtx = "1.10.1"

</pre>
<p>Наконец, библиотека объявляется в секции <span class="b">dependencies</span> файла Gradle уровня модуля:</p>
<pre class="brush:py;">
dependencies {

    implementation(libs.androidx.core.ktx)
    .........................................
}
</pre>
<p>Обратите внимание, что синтаксис ссылки на библиотеку в файле Gradle заключается в добавлении к имени, используемому в записи каталога <span class="b">[libraries]</span>, префикса "libs".</p>


	

