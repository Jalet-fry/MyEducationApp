<h3>Общий обзор Gradle</h3>
<p><span class="b">Gradle</span> представляет набор инструментов для автоматической сборки, который позволяет настраивать и управлять сборкой проектов с помощью специальных файлов конфигурации. 
В частности, можно задать, как будет собираться проект, какие зависимости необходимо добавить для успешной сборки и каким должен быть конечный результат (или результаты) процесса сборки. 
Правила конфигурации для сборки проекта объявляются в файлах сборки Gradle и сценариях на основе языка программирования Groovy. Стоит 
отметить, что в Android Studio интеграция Gradle обеспечивается через специальный одноименный плагин.</p>

<p>Gradle имеет предопределенный набор параметров конфигурации по умолчанию, которые будут использоваться, если только настройки в файлах сборки не переопределят их. 
Это означает, что сборки могут выполняться с минимальной конфигурацией, необходимой разработчику. Изменения в файлах сборки необходимы только в том случае, если конфигурация по 
умолчанию не соответствует текущим потребностям сборки.</p>

<p>Один из ключевых моментов конфигурации Gradle — это <span class="b">зависимости</span> - модули, которые необходимы для работы приложения и функционаьность которых используется в приложении. 
Зависимости Gradle можно разделить на локальные и удаленные. Локальная зависимость ссылается на элемент, присутствующий в локальной файловой системе на текущем компьютере, на котором 
выполняется сборка. Удаленная зависимость относится к элементу, который присутствует на удаленном сервере (обычно называемом репозиторием).</p>

<p>Удаленные зависимости для проектов Android Studio обрабатываются с помощью другого инструмента управления проектами под названием Maven. Если удаленная зависимость объявлена в 
файле сборки Gradle с использованием синтаксиса Maven, то зависимость будет автоматически загружена из назначенного репозитория и включена в процесс сборки.</p>

<p>Gradle также обеспечивает поддержку вариантов сборки для проектов Android Studio. Это позволяет создавать несколько вариантов приложения из одного проекта. 
Android работает на множестве различных устройств с разными типами процессоров и размерами экранов. Чтобы охватить как можно более широкий диапазон типов и размеров устройств, 
часто бывает необходимо создать несколько вариантов приложения (например, один с пользовательским интерфейсом для телефонов, а другой — для планшетов).</p>

<p>С каждым проектом Android Studio связан файл <span class="b">AndroidManifest.xml</span> (файл манифеста), который содержит сведения о конфигурации приложения. В файлах сборки Gradle можно указать 
несколько записей манифеста, которые затем автоматически генерируются в файл манифеста при сборке проекта. Эта возможность дополняет функцию вариантов сборки, 
позволяя настраивать такие элементы, как номер версии приложения, идентификатор приложения и информацию о версии SDK, для каждого варианта сборки.</p>
<p>ProGuard — это инструмент, включенный в Android Studio, который оптимизирует, сжимает и запутывает байт-код Java, чтобы сделать его более эффективным и трудным для дизассемблирования/декомпиляции. 
Файлы сборки Gradle позволяют контролировать, будет ли ProGuard запускаться при сборке проекта.</p>

<p>Сборки часто включают несколько инструментов для анализа, компиляции, компоновки и упаковки приложения или библиотеки. Для организации и выполнения этих команд Gradle использует подход на основе задач. 
<span class="b">Задачи</span> содержат команды, которые преобразуют входные данные в некоторый результат. Для определения задач и их конфигурации используются <span class="b">плагины</span>. 
Применение плагина к сборке регистрирует его задачи и связывает их вместе. Например, применение плагина Android Gradle (AGP) к файлу сборки зарегистрирует все задачи, необходимые для сборки файла APK или библиотеки.</p>


<h4>Процесс сборки с помощью Gradle</h4>
<p>Сборки Gradle выполняются в три фазы:</p>
<ul>
<li><p><span class="b">Инициализация</span>: определяет, какие проекты и подпроекты включены в сборку, и настраивает пути к файлам сборки и применяемым плагинам. Этот этап определяется в файле 
настроек, в котором объявляются проекты для сборки и пути к плагинам и библиотекам.</p></li>
<li><p><span class="b">Конфигурация</span>: регистрирует задачи для каждого проекта, выполняет файл сборки и применяет пользовательскую спецификацию сборки.</p></li>
<li><p><span class="b">Выполнение</span>: выполняет фактическую сборку приложения. Результат предыдущего этапа - конфигурации представляет собой направленный ациклический граф (DAG) задач, 
представляющий все требуемые шаги сборки (задачи, указанные в командной строке или в файлах сборки).</p></li>
</ul>
