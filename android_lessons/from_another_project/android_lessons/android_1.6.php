<h3>Свойства и настройки Gradle</h3>
<p>Файл <span class="b">gradle.properties</span> содержит в основном настройки флагов командной строки, используемым виртуальной машиной Java (JVM), а также указывают, 
использует ли проект библиотеки AndroidX и поддерживает ли стиль кодирования Kotlin:</p>
<pre class="brush:py;">
# Specifies the JVM arguments used for the daemon process.
# The setting is particularly useful for tweaking memory settings.
org.gradle.jvmargs=-Xmx2048m -Dfile.encoding=UTF-8
# When configured, Gradle will run in incubating parallel mode.
# This option should only be used with decoupled projects
# org.gradle.parallel=true
# AndroidX package structure to make it clearer which packages are bundled with the
# Android operating system, and which are packaged with your app's APK
android.useAndroidX=true
# Kotlin code style for this project: "official" or "obsolete":
kotlin.code.style=official
# Enables namespacing of each library's R class so that its R class includes only the
# resources declared in the library itself and none from the library's dependencies,
# thereby reducing the size of the R class for that library
android.nonTransitiveRClass=true
</pre>
<p>Обычно не требуется изменить какие-либо параметры в этом файле.</p>
<p>Файл <span class="b">settings.gradle.kts</span> определяет, какие онлайн-репозитории следует использовать, когда системе сборки необходимо загрузить и установить любые дополнительные 
библиотеки и плагины, необходимые для сборки проекта, а также имя проекта. Типичный файл <span class="b">settings.gradle.kts</span> выглядит следующим образом:</p>
<pre class="brush:py;">
pluginManagement {
    repositories {
        google {
            content {
                includeGroupByRegex("com\.android.*")
                includeGroupByRegex("com\.google.*")
                includeGroupByRegex("androidx.*")
            }
        }
        mavenCentral()
        gradlePluginPortal()
    }
}
dependencyResolutionManagement {
    repositoriesMode.set(RepositoriesMode.FAIL_ON_PROJECT_REPOS)
    repositories {
        google()
        mavenCentral()
    }
}

rootProject.name = "HelloApp"
include(":app")
</pre>

<h3>Файл Gradle проекта</h3>
<p>Каждый проект содержит один файл сборки Gradle верхнего уровня. Этот файл указан как <span class="b">build.gradle.kts</span> <span class="ii">(Project: &lt;имя проекта&gt;)</span></p>
<img src="./pics/20.2.png" alt="Файл build.gradle.kts проекта в Android Studio" />
<p>По умолчанию он имеет содержимое типа следующего:</p>
<pre class="brush:js;">
plugins {
    alias(libs.plugins.androidApplication) apply false
    alias(libs.plugins.jetbrainsKotlinAndroid) apply false
}
</pre>
<p>В большинстве случаев не требуется изменять данных файл.</p>

