<h3>Поиск в строке</h3>
<p>Метод <span class="b">indexOf()</span> находит индекс первого вхождения подстроки в строку, а метод <span class="b">lastIndexOf()</span> - индекс последнего вхождения. 
Если подстрока не будет найдена, то оба метода возвращают -1:</p>
<pre class="brush:java;">
String str = "Hello world";
int index1 = str.indexOf('l'); // 2
int index2 = str.indexOf("wo"); //6
int index3 = str.lastIndexOf('l'); //9
</pre>
<p>Метод <span class="b">startsWith()</span> позволяют определить начинается ли строка с определенной подстроки, а метод 
<span class="b">endsWith()</span> позволяет определить заканчивается строка на определенную подстроку:</p>
<pre class="brush:java;">
String str = "myfile.exe";
boolean start = str.startsWith("my"); //true
boolean end = str.endsWith("exe"); //true
</pre>
<h3>Замена в строке</h3>
<p>Метод <span class="b">replace()</span> позволяет заменить в строке одну последовательность символов на другую:</p>
<pre class="brush:java;">
String str = "Hello world";
String replStr1 = str.replace('l', 'd'); // Heddo wordd
String replStr2 = str.replace("Hello", "Bye"); // Bye world
</pre>
<h3>Удаление начальных и конечных пробелов</h3>
<p>Метод <span class="b">strip()</span> позволяет удалить начальные и конечные пробелы:</p>
<pre class="brush:java;">
String str = "   Hello METANIT.COM  ";
System.out.println(str.length());  // 22
str = str.strip(); 	// удаляем пробелы
System.out.println(str.length());  // 17
</pre>
<p>Стоит отметить, что ранее - в более ранних версиях Java для этой цели служил метод <code>trim()</code>, однако он не очень корректно работает с некоторыми символами Unicode, поэтому вместо него рекомендуется <code>strip()</code></p>

<p>Дополнительно метод <span class="b">stripLeading()</span> позволяет удалить только начальные, а метод <span class="b">stripTrailing()</span> - только конечные пробелы:</p>
<pre class="brush:java;">
String str = "   Hello METANIT.COM  ";
System.out.println(str.length());  // 22
str = str.stripLeading();   // удаляем начальные пробелы
System.out.println(str.length());  // 19
str = str.stripTrailing();   // удаляем конечные пробелы
System.out.println(str.length());  // 17
</pre>

<h3>Получение подстроки</h3>
<p>Метод <span class="b">substring()</span> возвращает подстроку, начиная с определенного индекса до конца или до определенного индекса:</p>
<pre class="brush:java;">
String str = "Hello world";
String substr1 = str.substring(6); // world
String substr2 = str.substring(3,5); //lo
</pre>
<h3>Изменение регистра</h3>
<p>Метод <span class="b">toLowerCase()</span> переводит все символы строки в нижний регистр, а метод <span class="b">toUpperCase()</span> -  в верхний:</p>
<pre class="brush:java;">
String str = "Hello World"; 
System.out.println(str.toLowerCase()); // hello world
System.out.println(str.toUpperCase()); // HELLO WORLD
</pre>
<h3>Split</h3>
<p>Метод <span class="b">split()</span> позволяет разбить строку на подстроки по определенному разделителю. Разделитель - какой-нибудь символ или набор символов 
передается в качестве параметра в метод. Например, разобьем текст на отдельные слова:</p>
<pre class="brush:java;">
String text = "FIFA will never regret it";
String[] words = text.split(" ");
for(String word : words){
	System.out.println(word);
}
</pre>
<p>В данном случае строка будет разделяться по пробелу. Консольный вывод:</p>
<pre class="sh">
FIFA
will
never
regret
it
</pre>

	

