	<h3>Соединение строк</h3>
<p>Для соединения строк можно использовать операцию сложения ("+"):</p>
<pre class="brush:java;">
String str1 = "Java";
String str2 = "Hello";
String str3 = str1 + " " + str2;
        
System.out.println(str3); // Hello Java
</pre>
<p>При этом если в операции сложения строк используется нестроковый объект, например, число, то этот объект преобразуется к строке:</p>
<pre class="brush:java;">String str3 = "Год " + 2015;</pre>
<p>Фактически же при сложении строк с нестроковыми объектами будет вызываться метод <span class="b">valueOf()</span> класса String. Данный метод 
имеет множество перегрузок и преобразует практически все типы данных к строке. Для преобразования объектов различных классов метод <code>valueOf</code> 
вызывает метод <span class="b">toString()</span> этих классов.</p>
<p>Другой способ объединения строк представляет метод <span class="b">concat()</span>:</p>
<pre class="brush:java;">
String str1 = "Java";
String str2 = "Hello";
str2 = str2.concat(str1); // HelloJava
</pre>
<p>Метод <code>concat()</code> принимает строку, с которой надо объединить вызывающую строку, и возвращает соединенную строку.</p>
<p>Еще один метод объединения - метод <span class="b">join()</span> позволяет объединить строки с учетом разделителя. Например, выше две строки 
сливались в одно слово "HelloJava", но в идеале мы бы хотели, чтобы две подстроки были разделены пробелом. И для этого используем метод <code>join()</code>:</p>
<pre class="brush:java;">
String str1 = "Java";
String str2 = "Hello";
String str3 = String.join(" ", str2, str1); // Hello Java
</pre>
<p>Метод <code>join</code> является статическим. Первым параметром идет разделитель, которым будут разделяться подстроки в общей строке, а все последующие параметры 
передают через запятую произвольный набор объединяемых подстрок - в данном случае две строки, хотя их может быть и больше</p>

<h3>Проверка на пустоту</h3>
<p>Метод <span class="b">isEmpty()</span> позволяет проверить, является ли строка пустой. Пустая строка не имеет никаких символов, однако она определена и не равна <code>null</code>:</p>
<pre class="brush:java;">
String str1 = "Hello";
System.out.println(str1.isEmpty());  // false
String str2 = "  \t\n";
System.out.println(str2.isEmpty());  // false
String str3 = "";
System.out.println(str3.isEmpty());  // true
</pre>
<p>Из кода выше мы можем увидеть, что даже если строка содержит пробельные символы, табуляцию, переводы строки, то она все равно считается НЕ пустой. 
Метод <span class="b">isBlank()<span> также позволяет проверить, является ли строка пустой, но теперь пустой считается строка, которая содержит также одни пробелы, табуляцию, переводы строки:</p>
<pre class="brush:java;">
String str1 = "Hello";
System.out.println(str1.isBlank());  // false
String str2 = "  \t\n";
System.out.println(str2.isBlank());  // true
String str3 = "";
System.out.println(str3.isBlank());  // true
</pre>

<h3>Извлечение символов и подстрок</h3>
<p>Для извлечения символов по индексу в классе String определен метод <span class="b">char charAt(int index)</span>. Он принимает индекс, по которому надо получить символов, 
и возвращает извлеченный символ:</p>
<pre class="brush:java;">
String str = "Java";
char c = str.charAt(2);
System.out.println(c); // v
</pre>
<p>Как и в массивах индексация начинается с нуля.</p>
<p>Если надо извлечь сразу группу символов или подстроку, то можно использовать метод <span class="b">getChars(int srcBegin, int srcEnd, char[] dst, int dstBegin)</span>. 
Он принимает следующие параметры:</p>
<ul>
<li><p><code>srcBegin</code>: индекс в строке, с которого начинается извлечение символов<p></li>
<li><p><code>srcEnd</code>: индекс в строке, до которого идет извлечение символов<p></li>
<li><p><code>dst</code>: массив символов, в который будут извлекаться символы<p></li>
<li><p><code>dstBegin</code>: индекс в массиве dst, с которого надо добавлять извлеченные из строки символы<p></li>
</ul>
<pre class="brush:java;">
String str = "Hello world!";
int start = 6;
int end = 11;
char[] dst=new char[end - start];
str.getChars(start, end, dst, 0);
System.out.println(dst); // world
</pre>
<h3>Сравнение строк</h3>
<p>Для сравнения строк используются методы <span class="b">equals()</span> (с учетом регистра) и <span class="b">equalsIgnoreCase()</span> (без учета регистра). 
Оба метода в качестве параметра принимают строку, с которой надо сравнить:</p>
<pre class="brush:java;">
String str1 = "Hello";
String str2 = "hello";
        
System.out.println(str1.equals(str2)); // false
System.out.println(str1.equalsIgnoreCase(str2)); // true
</pre>
<p>В отличие от сравнения числовых и других данных примитивных типов для строк не применяется знак равенства ==. Вместо него надо использовать метод 
<code>equals()</code>.</p>
<p>Еще один специальный метод <span class="b">regionMatches()</span> сравнивает отдельные подстроки в рамках двух строк. Он имеет следующие формы:</p>
<pre class="brush:java;">
boolean regionMatches(int toffset, String other, int oofset, int len)
boolean regionMatches(boolean ignoreCase, int toffset, String other, int oofset, int len)
</pre>
<p>Метод принимает следующие параметры:</p>
<ul>
<li><p><code>ignoreCase</code>: надо ли игнорировать регистр символов при сравнении. Если значение <code>true</code>, регистр игнорируется</p></li>
<li><p><code>toffset</code>: начальный индекс в вызывающей строке, с которого начнется сравнение</p></li>
<li><p><code>other</code>: строка, с которой сравнивается вызывающая</p></li>
<li><p><code>oofset</code>: начальный индекс в сравниваемой строке, с которого начнется сравнение</p></li>
<li><p><code>len</code>: количество сравниваемых символов в обеих строках</p></li>
</ul>
<p>Используем метод:</p>
<pre class="brush:java;">
String str1 = "Hello world";
String str2 = "I work";
boolean result = str1.regionMatches(6, str2, 2, 3);
System.out.println(result); // true
</pre>
<p>В данном случае метод сравнивает 3 символа с 6-го индекса первой строки ("wor") и 3 символа со 2-го индекса второй строки ("wor"). Так как 
эти подстроки одинаковы, то возвращается <code>true</code>.</p>
<p>И еще одна пара методов <span class="b">int compareTo(String str)</span> и <span class="b">int compareToIgnoreCase(String str)</span> также 
позволяют сравнить две строки, но при этом они также позволяют узнать больше ли одна строка, чем другая или нет. Если возвращаемое значение 
больше 0, то первая строка больше второй, если меньше нуля, то, наоборот, вторая больше первой. Если строки равны, то возвращается 0.</p>
<p>Для определения больше или меньше одна строка, чем другая, используется лексикографический порядок. То есть, например, строка "A" меньше, чем строка 
"B", так как символ 'A' в алфавите стоит перед символом 'B'. Если первые символы строк равны, то в расчет берутся следующие символы. Например:</p>
<pre class="brush:java;">
String str1 = "hello";
String str2 = "world";
String str3 = "hell";
        
System.out.println(str1.compareTo(str2)); // -15 - str1 меньше чем strt2
System.out.println(str1.compareTo(str3)); // 1 - str1 больше чем str3
</pre>

