<p>Ряд методов создания сегментов памяти в классе Arena принимают в качестве параметра объект типа <span class="b">MemoryLayout</span>. Этот интерфейс описывает компоновку памяти - размер сегмента памяти, выравнивание, порядок байтов.
Интерфейс <span class="b">ValueLayout</span> (который наследуется от <code>MemoryLayout</code>) предоставляет ряд констант, 
которые представляют встроенную компоновку памяти для определенного типа данных:</p>
<ul>
<li><p><code>ADDRESS</code>: константа компоновки адреса, размер которой совпадает с размером машинного адреса (<code>size_t</code> в языке С), выравнивание по байтам установлено равным <code>sizeof(size_t)</code></p></li>
<li><p><code>ADDRESS_UNALIGNED</code>: константа компоновки адреса без выравнивания, размер которой совпадает с размером машинного адреса (<code>size_t</code>)</p></li>
<li><p><code>JAVA_BOOLEAN</code>: константа компоновки значения, размер которой совпадает с размером типа <code>boolean</code> в Java, выравнивание по байтам установлено равным 1</p></li>
<li><p><code>JAVA_BYTE</code>: константа компоновки значения, размер которой совпадает с размером типа <code>byte</code> в Java, выравнивание по байтам установлено на 1</p></li>
<li><p><code>JAVA_CHAR</code>: константа компоновки значения, размер которой совпадает с размером типа <code>char</code> в Java, выравнивание по байтам установлено на 2</p></li>
<li><p><code>JAVA_CHAR_UNALIGNED</code>: константа компоновки адреса без выравнивания, размер которой совпадает с размером типа <code>char</code> в Java</p></li>
<li><p><code>JAVA_DOUBLE</code>: константа компоновки значений, размер которой совпадает с размером типа <code>double</code> в Java, выравнивание по байтам установлено на 8</p></li>
<li><p><code>JAVA_DOUBLE_UNALIGNED</code>: константа компоновки адреса без выравнивания, размер которой совпадает с размером типа <code>double</code> в Java</p></li>
<li><p><code>JAVA_FLOAT</code>: константа компоновки значений, размер которой совпадает с размером типа <code>float</code> в Java, выравнивание по байтам установлено на 4</p></li>
<li><p><code>JAVA_FLOAT_UNALIGNED</code>: константа компоновки адреса без выравнивания, размер которой совпадает с размером типа <code>float</code> в Java</p></li>
<li><p><code>JAVA_INT</code>: константа расположения значений, размер которой совпадает с размером типа <code>int</code> в Java, выравнивание байтов установлено на 4</p></li>
<li><p><code>JAVA_INT_UNALIGNED</code>: константа компоновки адреса без выравнивания, размер которой совпадает с размером типа <code>int</code> в Java</p></li>
<li><p><code>JAVA_LONG</code>: константа компоновки значений, размер которой совпадает с размером типа <code>long</code> в Java, выравнивание по байтам установлено на 8</p></li>
<li><p><code>JAVA_LONG_UNALIGNED</code>: константа компоновки адреса без выравнивания, размер которой совпадает с размером типа <code>long</code> в Java</p></li>
<li><p><code>JAVA_SHORT</code>: константа компоновки значений, размер которой совпадает с размером типа <code>short</code> в Java, выравнивание по байтам установлено на 2</p></li>
<li><p><code>JAVA_SHORT_UNALIGNED</code>: константа компоновки адреса без выравнивания, размер которой совпадает с размером типа <code>short</code> в Java</p></li>
</ul>


<p>Для выделения массива необходимо указать структуру элементов и количество элементов. Для этого можно использовать константы компоновки памяти, определенные в классе <span class="b">ValueLayout</span>. 
Например, выделим массив значений типа <code>double</code>:</p>
<pre class="brush:java;">
import java.lang.foreign.*;

public class Program {

    public static void main(String[] args) {

        try (Arena arena = Arena.ofConfined()) {

            // выделяем память для 16 значений double
            MemorySegment double_seg = arena.allocate(ValueLayout.JAVA_DOUBLE, 16);

            System.out.println(double_seg);   // MemorySegment{ kind: native, address: 0x7477a8184cb0, byteSize: 128 }
        } 
    }
}
</pre>
<p>Если у нас уже есть значения в массиве, можно использовать метод <code>allocateFrom()</code>:</p>
<pre class="brush:java;">
import java.lang.foreign.*;

public class Program {

    public static void main(String[] args) {

        try (Arena arena = Arena.ofConfined()) {

            double[] nums = {1.0, 2.0, 3.0, 4.0};
            // выделяем память для массива nums
            MemorySegment double_seg = arena.allocateFrom(ValueLayout.JAVA_DOUBLE, nums);

            System.out.println(double_seg);   // MemorySegment{ kind: native, address: 0x75f5cc1851a0, byteSize: 32 }
        } 
    }
}
</pre>

<h3>Работа с сегментами памяти</h3>
<p>Интерфейс <span class="b">MemorySegment</span> предоставляет множество методов для различных операций с данными в памяти. Рассмотрим некоторые из них:</p>
<ul>
<li><p><code>String getString(long offset)</code></p><p>преобразует строку UTF-8 в строку Java.</p></li>

<li><p><code><i>type</i> getAtIndex(ValueLayout.of<i>type</i> layout, long index)</code></p><p>считывает значение примитивного типа по заданному индексу массива.</p></li>

<li><p>void setAtIndex(ValueLayout.of<i>type</i> layout, long index, <i>type</i> value)</p><p>записывает значение примитивного типа по заданному индексу массива.</p></li>

<li><p><i>type</i> get(ValueLayout.of<i>type</i> layout, long offset)</p><p>считывает значение примитивного типа по заданному смещению.</p></li>

<li><p><code>void set(ValueLayout.of<i>type</i> layout, long offset, <i>type</i> value)</code></p><p>записывает значение примитивного типа по заданному смещению.</p></li>

<li><p><code><i>type</i>[] toArray(ValueLayout.of<i>type</i> elementLayout)</code></p><p>копирует содержимое сегмента памяти в массив примитивного типа type.</p></li>
</ul>

<p>Например, возьмем метод <code>getString()</code>. Предположим, что функция C заполнила сегмент памяти данными. Чтобы преобразовать строку UTF-8 в строку Java, в метод <code>getString()</code> передается 
смещение 0:</p>
<pre class="brush:java;">
import java.lang.foreign.*;

public class Program {

    public static void main(String[] args) {

        try (Arena arena = Arena.ofConfined()) {

            String str = "Hello METANIT.COM";

            // преобразуем строку Java в строку UTF-8
            MemorySegment str_seg = arena.allocateFrom(str);

            System.out.println(str_seg);   // MemorySegment{ kind: native, address: 0x7aa79c1802d0, byteSize: 18 }

            // обратное преобразование в строку Java
            String java_str = str_seg.getString(0);

            System.out.println(java_str);   // Hello METANIT.COM
        } 
    }
}
</pre>
<p>Для чтения или записи по индексу массива указывается структура памяти и индекс:</p>
<pre class="brush:java;">
import java.lang.foreign.*;

public class Program {

    public static void main(String[] args) {

        try (Arena arena = Arena.ofConfined()) {

            double[] nums = {1.0, 2.0, 3.0, 4.0};
            // выделяем память для массива nums
            MemorySegment double_seg = arena.allocateFrom(ValueLayout.JAVA_DOUBLE, nums);

            // устанавливаем для элемента с индексом 2 значение 5.0
            int index = 2;
            double_seg.setAtIndex(ValueLayout.JAVA_DOUBLE, index, 5.0);
            // получаем один элемент double по индексу 2
            double second_double = double_seg.getAtIndex(ValueLayout.JAVA_DOUBLE, index);

            System.out.println(second_double);  // 5.0
        } 
    }
}
</pre>
<p>Обратите внимание, что сегмент не сохраняет никакой информации о структуре данных внутри. Вам необходимо указывать структуру данных (в данном случае <code>ValueLayout.JAVA_DOUBLE</code>) 
при каждом доступе к элементам или при их обновлении.</p>
<p>Также можно получить массив Java со всеми значениями:</p>
<pre class="brush:java;">
double[] double_nums = double_seg.toArray(ValueLayout.JAVA_DOUBLE);
</pre>
<p>Методы <code>get()</code>/<code>set()</code> аналогичны методам <code>getAtIndex</code>/<code>setAtIndex</code>, но принимают смещение в байтах:</p>
<pre class="brush:java;">
import java.lang.foreign.*;

public class Program {

    public static void main(String[] args) {

        try (Arena arena = Arena.ofConfined()) {

            double[] nums = {1.0, 2.0, 3.0, 4.0};
            // выделяем память для массива nums
            MemorySegment double_seg = arena.allocateFrom(ValueLayout.JAVA_DOUBLE, nums);

            // устанавливаем значение 11 по смещению 8 байт
            double_seg.set(ValueLayout.JAVA_DOUBLE, 8, 11);
            // получаем один элемент double по смещению 16 байт
            double second_double = double_seg.get(ValueLayout.JAVA_DOUBLE, 16);

            System.out.println(second_double);  // 3.0
        } 
    }
}
</pre>

	

