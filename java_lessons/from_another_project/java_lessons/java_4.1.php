<h2>Генерация исключения и оператор throw</h2>
<p>Обычно система сама генерирует исключения при определенных ситуациях, например, при делении числа на ноль. Но язык Java также позволяет генерировать исключения вручную с помощью оператора <b>throw</b>. 
Например, в нашей программе пользователь должен вводить имя, но имя имеет свои ограничения. Например, очевидно, что имя из одного символа - это некорректно имя. Возможно, мы предъявляем еще какие-то ограничения к  
имени. И в этом случае мы можем при вводе некорректных данных генерировать исключение.</p>
<p>Общая форма оператора:</p>
<pre class="brush:java;">
throw объект_исключения;
</pre>
<p>То есть после оператора указывается объект исключения. Как его создать? Прежде всего мы можем использовать встроенные классы исключений, в том числе базовые - <code>Throwable</code> и <code>Exception</code>. 
Так, один из конструкторов типа <code>Throwable</code> принимает сообщение об ошибке:</p>
<pre class="brush:java;">
Throwable(String message)
</pre>
<p>По сути это то сообщение, которое возвращается методом <code>getMessage()</code> и которое при возникновении ошибки отображается на консоли. Ну и соответственно все другие типы исключений также имеют подобный конструктор.</p>
<p>Рассмотрим генерацию исключения на примере:</p>
<pre class="brush:java;">
import java.util.Scanner;

class Program{
     
	public static void main(String[] args) {
         
        Scanner in = new Scanner(System.in);
        System.out.print("Введите имя: ");
        String name = in.nextLine(); // считываем введенную строку

        // если строка имеет имеет меньше 2-х символов, генерируем исключение
        if(name.length() &lt; 2) throw new Throwable("Малобукоф");

        System.out.println("Привет, " + name);
    }
}
</pre>
<p>Здесь с помощью класса <code>Scanner</code> и метода <code>in.nextLine()</code> считываем с консоли строку - условное имя пользователя. Затем, используя метол <code>length()</code> у строки смотрим на длину - 
если в имени меньше 2 символов, то генерируем исключение:</p>
<pre class="brush:java;">if(name.length() &lt; 2) throw new Throwable("Малобукоф");</pre>
<p>В конструктор класса <code>Throwable</code> передаем сообщение об ошибке.</p>
<p>Но если мы попробуем скомпилировать программу, нас постигнет неудача:</p>
<pre class="sh">
Program.java:12: error: unreported exception Throwable; must be caught or declared to be thrown
        if(name.length() &lt; 2) throw new Throwable("Малобукоф");
                              ^
1 error
</pre>
<p>Компилятор нам говорит, что нам надо либо обработать исключение, либо указать, что метод main генерирует данное исключение.</p>
<h3>Проверяемые и непроверяемые исключения</h3>
<p>КАк говорилось в прошлой статье, исключения в Java делятся условно на две группы: <span class="b">проверяемые</span> (checked exceptions) и <span class="b">непроверяемые</span> 
 (unchecked exceptions). К <span class="b">непроверяемым исключениям</span> относят классы <b>Error</b> и <b>RuntimeException</b> и унаследованные от них классы. А проверяемые исключения по сути все остальные. 
И в контексте работы с оператором <code>throw</code> подобное разделение имеет большое значение. При генерации <span class="b">проверяемых исключений</span> нам надо либо указать, что метод генерирует исключение, либо обработать это исключение. Если же генерируются 
<b>непроверяемые исключения</b>, то ничего этого делать не надо.</p>
<p>В нашем примере выше генерируемое исключение типа <code>Throwable</code> рассматривается компилятором как <b>проверяемое исключение</b> (хотя классы <code>Error</code> и <code>RuntimeException</code> 
унаследованы от <code>Throwable</code>). Поэтому и при компиляции возникает ошибка.</p>


<p>Для решения проблемы изменим код и обработаем исключение с помощью рассмотренной в прошлых статьях конструкции <code>try..catch</code>:</p>
<pre class="brush:java;">
import java.util.Scanner;

class Program{
     
	public static void main(String[] args) {
         
        Scanner in = new Scanner(System.in);
        System.out.print("Введите имя: ");
        String name = in.nextLine(); // считываем введенную строку

        try{

            // если строка имеет имеет меньше 2-х символов, генерируем исключение
            if(name.length() &lt; 2) throw new Throwable("Малобукоф");
            System.out.println("Привет, " + name);
        }
        catch(Throwable ex){
            System.out.println("Возникла ошибка: " + ex.getMessage());
        }
    }
}
</pre>
<p>Здесь та, часть кода, которая генерирует исключения и которая зависит от проверки переменной name, помещается в блок <code>try</code>. 
Если будет сгенерировано исключение, то управление перейдет к блоку <code>catch</code>, где мы перехватим исключение и выведем сообщение об ошибке.</p>
<p>Пример работы программы:</p>
<pre class="sh">
Введите имя: e
Возникла ошибка: Малобукоф
</pre>

<h3>Обработка других типов исключений</h3>
<p>Подобным образом мы можем генерировать исключения в любом месте программы. Кроме того, мы можем использовать и другие встроенные типы исключений. Например, встроенный тип 
<code>IllegalArgumentException</code> предназначен для генерации исключения при некорректном параметре метода. Используем данный тип:</p>
<pre class="brush:java;">
class Program{
     
	public static void main(String[] args) {
         
        var tom = new Person("Tom", -20);
        tom.print();
    }
}

class Person{
    
    private String name;
    private int age;

    Person(String name, int age){

        if(age &lt; 1 || age &gt; 110) throw new IllegalArgumentException("Некорректный возраст: " + age);
        this.name = name; 
        this.age = age;
    }

    void print(){ System.out.printf("Name: %s; Age: %d\n", name, age); }
}
</pre>
<p>Здесь в конструктор класса Person через параметр <code>age</code> передается возраст человека. Однако не все значения типа <code>int</code> могут быть разумными значениями для возраста. Например, 
возраст не может быть отрицательным. И в конструкторе класса Person проверяем значение параметра <code>age</code> на соответствие некоторому диапазону. Ив случае несоответствия, генерируем исключение 
типа <code>IllegalArgumentException</code></p>
<pre class="brush:java;">
if(age &lt; 1 || age &gt; 110) 
    throw new IllegalArgumentException("Некорректный возраст: " + age);
</pre>
<p>В методе <code>main</code> передаем в конструктор Person заведомо некорректное значение:</p>
<pre class="brush:java;">var tom = new Person("Tom", -20);</pre>
<p>В итоге при запуске программы и создании этого объекта будет сгенерировано исключение</p>
<pre class="sh">
Exception in thread "main" java.lang.IllegalArgumentException: Некорректный возраст: -20
	at Person.&lt;init&gt;(Program.java:20)
	at Program.main(Program.java:7)
</pre>
<p>Обратите внимание, что при компиляции программы компилятор не выдал ошибку, как при компиляции предыдущего примера. Потому что в данном случае мы обрабатываем исключение типа 
<code>IllegalArgumentException</code>, которое является <b>непроверяемым</b>. Поэтому в принципе его можно не обрабатывать, если нас устраивает подобное завершение программы с ошибкой. Тем не менее обработаем исключением:</p>
<pre class="brush:java;">
class Program{
     
	public static void main(String[] args) {
         
        try{

            var tom = new Person("Tom", -20);
            tom.print();
        }
        catch(IllegalArgumentException ex){
            System.out.println(ex.getMessage());
        }
    }
}

class Person{
    
    private String name;
    private int age;

    Person(String name, int age){

        if(age &lt; 1 || age &gt; 110) throw new IllegalArgumentException("Некорректный возраст: " + age);
        this.name = name; 
        this.age = age;
    }

    void print(){ System.out.printf("Name: %s; Age: %d\n", name, age); }
}
</pre>

