<h2>Оператор throws</h2>
<p>Если метод генерирует <b>проверяемое исключение</b>, то нам надо либо обработать это исключение, либо сообщить компилятору, что метод генерирует данное исключение. 
Поэтому обработка исключения непосредственно в методе - не единственный способ работы с проверяемыми исключениями. Нередко метод сам не обрабатывает исключение, а предоставляет возможность обработки внешнему коду, 
где этот метод вызывается. В этом случае в объявлении метода необходимо указать тип исключения, который генерирует метод. Для этого используется 
оператор <span class="b">throws</span> в следующем виде:</p>
<pre class="brush:java;">
возвращаемый_тип имя_метода(параметры) throws тип_исключения_1, тип_исключения_2,... тип_исключения_N  {

}
</pre>
<p>Оператор <span class="b">throws</span> указывается после списка параметров метода, но до открывающей фигурной скобки. А после оператора идет перечисление типов генерируемых исключений. Например:</p>
<pre class="brush:java;">
import java.util.Scanner;

class Program{
     
	public static void main(String[] args) {
         
        try{
            printName();  // здесь генерируется исключение
        }
        catch(Throwable ex){
            System.out.println(ex.getMessage());
        }
    }

    static void printName() throws Throwable {

        Scanner in = new Scanner(System.in);
        System.out.print("Введите имя: ");
        String name = in.nextLine(); // считываем введенную строку

        // если строка имеет имеет меньше 2-х символов, генерируем исключение
        if(name.length() &lt; 2) throw new Throwable("Недостаточная длина имени: " + name.length());
        System.out.println("Привет, " + name);
    }
}
</pre>
<p>Здесь метод <code>printName()</code> считывает через консоль имя пользователя и с помощью оператора <code>throw</code> генерирует исключение типа <code>Throwable</code>, если длина введенного имени меньше 2 символов. 
При этом, поскольку этот метод сам не обрабатывает исключение, то в объявлении метода указываем, что он генерирует исключение типа <code>Throwable</code>:</p>
<pre class="brush:java;">static void printName() throws Throwable {</pre>
<p>А внешний метод - <code>main()</code>, в котором вызывается <code>printName()</code>, обрабатывает возможно исключение с помощью конструкции <code>try..catch</code>.</p>

<p>ПРи этом следует учитывать, что если вызываемый метод (<code>printName()</code>) сам не обрабатывает <b>проверяемое исключение</b>, то внешний - вызывающий метод (<code>main()</code>) должен 
либо обработать исключение (как в примере выше), либо также указать компилятору с помощью оператора <code>throws</code>, что он генерирует данный тип исключений.</p>
<p>Выше был пример, где внешний метод <code>main()</code> обрабаотывал исключение, возникшее в <code>printName()</code>. Теперь же используем другую стратегию:</p>
<pre class="brush:java;">
import java.util.Scanner;

class Program{
     
	public static void main(String[] args) throws Throwable {
         
        printName(); // здесь возникает исключение, но его никто не обрабатывает
    }

    static void printName() throws Throwable{

        Scanner in = new Scanner(System.in);
        System.out.print("Введите имя: ");
        String name = in.nextLine(); // считываем введенную строку

        // если строка имеет имеет меньше 2-х символов, генерируем исключение
        if(name.length() &lt; 2) throw new Throwable("Недостаточная длина имени: " + name.length());
        System.out.println("Привет, " + name);
    }
}
</pre>
<p>Данная программа успешно скомпилируется, так как в заголовке метода <code>main()</code> мы указали выражение <code>throws Throwable</code>:</p>
<pre class="brush:java;">
public static void main(String[] args) throws Throwable { 
</pre>
<p>Однако при выполнении при некорректном вводе, поскольку исключение не обрабатывается, программа упадет с ошибкой:</p>
<pre class="sh">
Введите имя: r
Exception in thread "main" java.lang.Throwable: Недостаточная длина имени: 1
	at Program.printName(Program.java:22)
	at Program.main(Program.java:7)
</pre>
<p>И в конце стоит отметить, что метод может генерировать несколько типов исключений. В этом случае они указываются после оператора <code>throws</code> через запятую:</p>
<pre class="brush:java;">
public static void main(String[] args) throws FileNotFoundException, EOFException { 
</pre>
<p>Однако если метод генерирует <b>непроверяемые исключения</b> типа <code>IllegalArgumentException</code>, то нет смысла их указывать, так как компилятор их все равно не проверяет.</p>

	

