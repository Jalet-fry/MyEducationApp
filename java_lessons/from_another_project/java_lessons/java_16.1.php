<h3>Компиляция библиотеки на Си</h3>
<p>Итак, у нас есть заголовочный файл и файл кода C, и теперь нам надо скомпилировать весь этот нативный код на языке C в динамически загружаемую библиотеку. Конкретные подробности зависят от выбранного компилятора. 
В данном случае посмотрим, как это сделать, используя 2 распространенных компилятора.</p>
<p>Так, при использовании компилятора <span class="b">GCC</span> на Linux команда компиляции будет выглядеть следующим образом:</p>
<pre class="sh">
gcc -fPIC -I $JAVA_HOME/include -I $JAVA_HOME/include/linux -shared -o libHelloNative.so HelloNative.c
</pre>
<p>Здесь стоит учитывать, что переменная окружения <code>$JAVA_HOME</code> должна быть определена и указывать на папку установки java. Соответственно путь 
<code>$JAVA_HOME/include</code> будет указывать на папку с заголовочными файлами, которые необходимы для компиляции библиотеки на C, в частности, файл <span class="b">jni.h</span>, который подключался выше в одном из файлов. 
Тем не менее эта переменная может быть и не установлена, в этом случае (если нет желания устанавливать переменную <code>$JAVA_HOME</code>) можно передать конретный путь к папке, где располагаются заголовочные файлы. 
Например, если java локально установлена в каталоге  "/usr/java/jdk-25", то соответственно нам надо прописать</p>
<pre class="sh">
gcc -fPIC -I /usr/java/jdk-25/include -I /usr/java/jdk-25/include/linux -shared -o libHelloNative.so HelloNative.c
</pre>
<p>В любом случае после выполнения этой команды в текущей папке должен появиться файл библиотеки <span class="b">libHelloNative.so</span> (название самой библиотеки - "HelloNative" - без префикса "lib" и расширения файла)</p>
<p>Если текущая ОС - Windows и компилятор - VisualC++ от Microsoft, то там мы могли бы выполнить следующую команду</p>
<pre class="sh">
cl -I %JAVA_HOME%\include -I %JAVA_HOME%\include\win32 -LD HelloNative.c -FeHelloNative.dll
</pre>
<p>В этом случае в текущей папке появится файл "HelloNative.dll" ((название самой библиотеки также "HelloNative").</p>
<h3>Определение кода Java</h3>
<p>Для загрузки библиотеки нам надо добавить в код программы вызов метода <span class="b">System.loadLibrary</span>, в который передается название библиотеки. 
Чтобы гарантировать загрузку библиотеки виртуальной машиной до первого использования класса, можно использовать блок статической инициализации. Например, определим в текущей папке следующий файл <span class="b">Program.java</span>:</p>
<pre class="brush:java;">
class Program {
  
    public static void main(String[] args) {
        
        HelloNative.printf("Hello METANIT.COM\n");    
    }

    static {  
        System.loadLibrary("HelloNative");
    }
}
</pre>
<p>Таким образом, в папке проекта у нас будут следующие файлы:</p>
<ul>
<li><p><code>HelloNative.java</code>: класс с нативным методом-оберткой для функции языка Си</p></li>
<li><p><code>HelloNative.class</code>: скомпилированный класс</p></li>
<li><p><code>HelloNative.h</code>: автосгенерированный заголовочный файл</p></li>
<li><p><code>HelloNative.c</code>: реализация функции из заголовочного файла</p></li>
<li><p><code>libHelloNative.so</code>/<code>HelloNative.dll</code>: скомпилированная библиотека</p></li>
<li><p><code>Program.java</code>: основной файл программы</p></li>
</ul>
<h3>Запуск программы</h3>
<p>Скомпилируем программу на Java стандартной командой</p>
<pre class="sh">javac Program.java</pre>
<p>Для запуска программы прежде всего нам надо передать утилите java дополнительную опцию, которая как-бы разрешает использование нативного кода в программе на Java. Если модули не используются, то программа запускается следующим образом:</p>
<pre class="sh">java --enable-native-access=ALL-UNNAMED ...</pre>
<p>В модульной же программе необходимо перечислить все модули, для которых разрешен нативный доступ:</p>
<pre class="sh">java --enable-native-access=module1, module2 ...</pre>

<p>При запуске на Linux также необходимо добавить текущий каталог в путь к библиотекам, чтобы java нашла нашу библиотеку. Для этого можно установить переменную среды <span class="b">LD_LIBRARY_PATH</span>:</p>
<pre class="sh">export LD_LIBRARY_PATH=.:$LD_LIBRARY_PATH</pre>
<p>Здесь с помощью точки указываем текущую папку. Либо можно использовать системное свойство <code>java.library.path</code>:</p>
