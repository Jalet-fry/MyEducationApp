<p>Мы можем написать всю программу целиком на Java, учитывая большие возможности языка, большое количество досьупных фреймворков и библиотек на этом языке. Но бывают ситуации, когда 
может потребоваться одновременно вместе с кодом на Java использовать также код на другом языке, в частности, на C/C++. Например, если приложению требуется доступ к системным функциям или устройствам, недоступным через платформу Java, 
либо если уже имеется значительный объем протестированного и отлаженного кода на другом языке, который надо интегрировать в программу на языке Java. Поэтому рассмотрим как мы можем взаимодействовать в программе на Java 
с нативным кодом на C/C++</p>
<p>Начиная уже с версии Java 1.1 платформа Java имеет специальный API для взаимодействия с нативным кодом C, который называется <span class="b">Java Native Interface (JNI)</span>. Начиная с версии Java 20 был добавлен новый, более простой и удобный 
API - Foreign Functions and Memory API (FFM API). Тем не менее <span class="b">JNI</span> по прежнему может использоваться, особенно на старых версиях платформы. Поэтому вначале вкратце рассмотрим, базовые моменты 
<span class="b">JNI</span></p>
<p>Общий процесс связывания нативного метода с Java-программой с помощью JNI выглядит следующим образом:</p>
<ol>
<li><p>Объявляем нативный метод-обертку для функции Си в Java-классе.</p></li>
<li><p>С помощью команды <code>javac -h</code> генерируем заголовочный файл с объявлением метода на языке C.</p></li>
<li><p>Определяем код для нативного метода на языке C.</p></li>
<li><p> Компилируем код на Си в разделяемую библиотеку.</p></li>
<li><p>Загружаем эту библиотеку в программе на Java</p></li>
</ol>
<p>Рассмотрим по шагово весь процесс.</p>

<h3>Определение обертки функции на Java</h3>
<p>При использовании JNI для функции языка C/C++, которую мы хотим использовать, необходимо объявить прокси-метод с помощью ключевого слова <span class="b">native</span>. Это ключевое слово сообщает компилятору, что метод будет определен извне. Нативные методы не содержат кода Java, и за заголовком метода сразу следует точка с запятой. 
Поэтому объявления нативных методов выглядят аналогично объявлениям абстрактных методов.</p>

<p>Предположим, есть функция на языке C, которую необходимо использовать в коде на языке Java. Для наглядности возьмем стандартную библиотечную функцию <span class="b">printf</span> с одним аргументом и для ее применения определим 
файл <span class="b">HelloNative.java</span> со следующим кодом на языке Java:</p>
<pre class="brush:java;">
class HelloNative {  
    public static native int printf(String str);
}
</pre>
<p>Здесь определен класс HelloNative с одним нативным методов, имя которого соответствует названию функции <code>printf</code>. Нативные методы могут быть как статическими, так и нестатическими. В данном случае нативный метод также объявлен как статический.</p>
<p>Далее нам надо определить заголовочный файл на языке С. Для этого необходимо скомпилироть данный класс с флагом <span class="b">-h</span>, указав каталог, в который должны быть помещены заголовочные файлы:</p>
<pre class="sh">javac -h . HelloNative.java</pre>
<p>В итоге будет скомпилирован файл <span class="b">HelloNative.h</span> со следующим кодом:</p>
<pre class="brush:c;">
/* DO NOT EDIT THIS FILE - it is machine generated */
#include &lt;jni.h&gt;
/* Header for class HelloNative */

#ifndef _Included_HelloNative
#define _Included_HelloNative
#ifdef __cplusplus
extern "C" {
#endif
/*
 * Class:     HelloNative
 * Method:    printf
 * Signature: (Ljava/lang/String;)I
 */
JNIEXPORT jint JNICALL Java_HelloNative_printf
  (JNIEnv *, jclass, jstring);

#ifdef __cplusplus
}
#endif
#endif
</pre>
<p>Данный файл содержит объявление функции <code>Java_HelloNative_printf</code>. Причем обратите внимание, как называется функция: "Java_HelloNative_printf", а не просто "printf". 
В JNI имена функций строго регламентированы: сначала а добавляется префикс "Java", затем добавляется пакет класса (если пакет вложенный, например, "com.metanit.test", то в полном названии пакета точка заменяется на прочерк - "com_metanit_test") и 
в конце добавляется название класса и название функции через подчеркивание. То есть получается: <code>Java_</code> + <code>ИмяКласса_</code> + <code>ИмяМетода</code>. Значит, в Java этот метод объявлен в классе <code>HelloNative</code> как <code>native int printf(String s)</code></p>
<p>В принципе мы могли бы и вручную прописать подобный файл, но всегда есть вероятность ошибиться, поэтому лучше использовать автогенерацию.</p>

<h3>Определение кода на Си</h3>
<p>Далее определим еще один файл - <span class="b">HelloNative.c</span> со следующим кодом на языке С:</p>
<pre class="brush:c;">
#include "HelloNative.h"
#include &lt;stdio.h&gt;

JNIEXPORT jint JNICALL Java_HelloNative_printf (JNIEnv *env, jclass cl, jstring jstr) {

    const char *cstr = (*env)-&gt;GetStringUTFChars(env, jstr, NULL);
    int numchars = printf(cstr);
    (*env)-&gt;ReleaseStringUTFChars(env, jstr, cstr);
    return numchars;
}
</pre>
<p>Рассмотрим подробно, что происходит в каждой строке:</p>
<ol>
<li><p><code>#include "HelloNative.h</code></p>
<p>Прежде всего подключаем наш автосгенерированный заголовочный файл, чтобы Java смогла определить функцию при ее вызове.</p></li>

<li><p><code>#include &lt;stdio.h&gt;</code></p>
<p>Подключение стандартного заголовочного файла языка С, который содержит прототипы функций для работы с подсистемой ввода-вывода</p></li>

<li><p><code>JNIEXPORT jint JNICALL Java_HelloNative_printf</code></p>
<p><code>JNIEXPORT</code> и <code>JNICALL</code> - это специальные макросы, которые гарантируют, что функция будет видна Java-машине (JVM) и будет использовать правильное соглашение о вызовах. 
Между макросами указан возвращаемый тип - <code>jint</code>, которому в языке Java соответствует <code>int</code>. И после макросов идет имя функции - <code>Java_HelloNative_printf</code> и ее определение.</p></li>
<li><p><code>(JNIEnv *env, jclass cl, jstring jstr) </code></p>
<p>Каждая нативная функция получает параметр <code>env</code>, который необходим для доступа к API языка Си для нативных вызовов.</p>
<p>Параметр <code>cl</code> - это дескриптор Java-класса (для нестатических методов этому параметру передается дескриптор объекта).</p>
<p>Параметр <code>jstr</code> типа <code>jstring</code> - собственно то значение (строка), которое будет передаваться при вызове данного метода в коде Java.</p>
</li>

<li><p>Далее идет собственно код метода. И начинается он с получения строки (<code>GetStringUTFChars</code>)</p>
<p><code>const char *cstr = (*env)-&gt;GetStringUTFChars(env, jstr, NULL);</code></p>
<p>В Java строки хранятся в формате Unicode, а функции C (как <code>printf</code>) работают с массивами <code>char</code>.</p>
<p>Эта строка конвертирует Java-строку (<code>jstring</code>) в стандартную C-строку (UTF-8).</p>
</li>
<li><p>Вывод на экран</p>
<p><code>int numchars = printf(cstr);</code></p>
<p>Здесь вызывается стандартная функция языка C <code>printf</code>. Она выводит строку в консоль. Переменная <code>numchars</code> сохраняет количество напечатанных символов.</p>
</li>
<li><p>Освобождение памяти (<code>ReleaseStringUTFChars</code>)</p>
<p><code>(*env)-&gt;ReleaseStringUTFChars(env, jstr, cstr);</code></p>
<p>Это критически важный шаг. Поскольку JNI выделил память под <code>cstr</code>, ее необходимо освободить вручную, чтобы избежать утечек памяти.</p>
<p>Виртуальная машина должна знать, когда мы закончили использовать строку, чтобы она могла выполнить сборку мусора. Поскольку сборщик мусора работает в отдельном потоке и может прерывать выполнение нативных методов, 
то необходимо вызвать функцию <code>ReleaseStringUTFChars</code>.</p>
</li>
<li><p>Возврат значения</p>
<p><code>return numchars;</code></p>
<p>Количество напечатанных символов возвращается обратно в Java-код.</p>
</li>
</ol>

