<h3>Wildcard, ограниченный базовым классом (? extends Type)</h3>
<p>Wildcard, ограниченный "сверху" или ограниченный базовым классом, означает "любой тип, который представляет данный базовый класс или его производный класс. Задается в виде следующего выражения:</p>
<pre class="brush:java;">? extends Type</pre>
<p>То есть тип должен представлять производный от Type тип или сам Type</p>
<p>Данный тип подстановочных знаков применяется, когда вам нужно получать значение обобщения и работать с ним как с базовым типом.</p>
<p>Почему называется ограничением "сверху"? Потому что в иерархии типов базовые типы располагаются вверху. Соответственно тип Type задает крайний вверху базовый класс. Классы, которые расположены выше Type (базовые классы по отношению к Type, например, 
Object) отсекаются.</p>
<p>Например, определим метод, который работает только с теми объектами Person, у которых поле <code>id</code> представляет число, например, <code>Integer</code>, <code>Double</code>. 
Отличительная особенность встроенных числовых типов в Java в том, что они наследуются от базового класса <b>Number</b>. Поэтому мы можем использовать тип <code>Number</code> в качестве ограничения сверху:</p>
<pre class="brush:java;">
public class Program{
       
    public static void main(String[] args) {
           
        Person&lt;Integer&gt; tom = new Person&lt;&gt;(10, "Tom");
        Person&lt;Double&gt; bob = new Person&lt;&gt;(25.5, "Bob");

        processNumericId(tom);      // Id as double: 10.0
        processNumericId(bob);      // Id as double: 25.5
    }

    static void processNumericId(Person&lt;? extends Number&gt; person) {
        // Мы можем безопасно "прочитать" id как Number
        Number id = person.getId();
        System.out.println("Id as double: " + id.doubleValue());
    }
}
</pre>
<p>Здесь метод <code>processNumericId()</code> принимает объект Person, который типизирован типом NUmber или его наследниками:</p>
<pre class="brush:java;">void processNumericId(Person&lt;? extends Number&gt; person) </pre>
<p>Благодаря этому компилятор внутри метода будет рассматривать поле id (которое имеет тип T) как поле типа <code>Number</code>. Поэтому мы сможем внутри метода работать с id как с объектом типа Number, например, 
вызвать его метод <code>doubleValue()</code> для получения id в виде double.</p>
<p>Однако мы не можем написать следующим образом:</p>
<pre class="brush:java;">
public static void main(String[] args) {
           
    Person&lt;String&gt; sam = new Person&lt;&gt;("A-456", "Sam");
    Person&lt;Object&gt; alice = new Person&lt;&gt;(123, "Alice");

    processNumericId(sam);      // ! Ошибка
    processNumericId(alice);    // ! Ошибка
}
</pre>
<p>В первом случае (<code>processNumericId(sam)</code>) объект Person типизирован типом <code>String</code>, а <code>String</code> не входит в иерархию типа <code>Number</code>. Поэтому получаем ошибку.</p>
<p>Во втором случае (<code>processNumericId(alice)</code>) объект Person типизирован типом <code>Object</code>. Однако в иерархии типов тип <code>Object</code> располагается выше типа <code>Number</code> 
(является его базовым классом). Поэтому также получаем ошибку.</p>
<p>Также мы не можем установить id, даже если будем использовать объект Number:</p>
<pre class="brush:java;">
static void setNumericId(Person&lt;? extends Number&gt; person, Number id) {
        
    person.setId(id);  // ! Ошибка
}
</pre>
<p>Компилятор не знает, что именно ожидает объект — <code>Integer</code> или <code>Double</code>, поэтому не позволит установить какое-либо конкретное значение.</p>

<h3>Wildcard с ограничением производным типом (? super Type)</h3>

<p>Wildcard, ограниченный "снизу" или ограниченный производным типом, означает "любой тип, который представляет данный тип или его базовый тип. Под базовым типом понимается любой тип, 
который расположен выше по иерархии (например, для типа <code>Integer</code> - это <code>Number</code> (прямой базовый тип) и <code>Object</code> (непрямой базовый тип)). Задается в виде следующего выражения:</p>
<pre class="brush:java;">? super Type</pre>
<p>То есть тип должен представлять сам Type, либо его базовый тип (супертип). Поэтому все типы-наследники от самого Type в данном случае отсекаются.</p>
<p>Допустим, нам нужен метод для обновления <code>id</code>, который представлять тип <code>Integer</code>, либо его базовый класс (<code>Number</code>, <code>Object</code>). В этом случае мы можем установить ограничение снизу в виде типа <code>Integer</code>:</p>
<pre class="brush:java;">
public class Program{
       
    public static void main(String[] args) {
           
        Person&lt;Integer&gt; pInt = new Person&lt;&gt;(1, "Tom");
        Person&lt;Number&gt; pNum = new Person&lt;&gt;(2.0, "Bob");
        Person&lt;Object&gt; pObj = new Person&lt;&gt;("F-456", "Sam");

        setIntegerId(pInt, 100); // OK
        setIntegerId(pNum, 200); // OK
        setIntegerId(pObj, 300); // OK

        // проверка
        System.out.println("pInt Id: " + pInt.getId()); // pInt Id: 100
        System.out.println("pNum Id: " + pNum.getId()); // pNum Id: 200
        System.out.println("pObj Id: " + pObj.getId()); // pObj Id: 300
    }
    static void setIntegerId(Person&lt;? super Integer&gt; person, int newId) {
        // Мы можем безопасно "записать" Integer,
        // так как любой супертип Integer сможет его принять.
        person.setId(newId);
    }
}
</pre>
<p>Здесь определен метод <code>setIntegerId()</code>, который получает объект Person и новое значение id для установки. Такой метод сможет работать с типами <code>Person&lt;Integer&gt;</code>, <code>Person&lt;Number&gt;</code> и <code>Person&lt;Object&gt;</code>.</p>
<p>Однако при чтении (например, при вызове <code>getId()</code>) мы можем быть уверены только в том, что получим <code>Object</code>, так как неизвестно, какой именно супертип используется (<code>Integer</code>, <code>Number</code> или <code>Object</code>):</p>
<pre class="brush:java;">
public class Program{
       
    public static void main(String[] args) {
           
        Person&lt;Integer&gt; pInt = new Person&lt;&gt;(1, "Tom");
        Person&lt;Number&gt; pNum = new Person&lt;&gt;(2.0, "Bob");
        Person&lt;Object&gt; pObj = new Person&lt;&gt;("F-456", "Sam");

        printPersonId(pInt);
        printPersonId(pNum);
        printPersonId(pObj);
    }

    static void printPersonId(Person&lt;? super Integer&gt; person) {

        // Здесь id - это Object
        Object id = person.getId();

        // Integer id = person.getId();  // так мы не можем написать

        System.out.println(id); 
    }
}
</pre>
<h3>Принцип PECS</h3>
<p>Принцип <b>PECS</b> (Producer Extends, Consumer Super) представляет простое правило помогает запомнить, когда какой wildcard использовать:</p>
<ul>
<li><p><span class="b">Producer extends</span>: объект <span class="b">поставляет</span> данные (операции чтения, как в <code>getId()</code>). В этом случае случае используется <code>? extends Type</code></p></li>
<li><p><span class="b">Consumer super</span>: объект <span class="b">потребляет</span> данные (операции записи, как в <code>setId()</code>). В этом случае случае используется <code>? super Type</code></p></li>
</ul>
	

