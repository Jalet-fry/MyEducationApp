<p>В языке Java обобщения играют важную роль в обеспечении безопасности типов и создании гибкого кода. 
Однако, при работе с наследованием и обобщениями могут возникать сложности. Именно здесь на помощь приходят <b>wildcards</b> (подстановочные знаки или метасимволы), предоставляя мощный инструмент 
для работы с неизвестными типами.</p>


<p>В контексте обобщений wildcard или подстановочный знак представляет представляет неизвестный тип и обозначается с помощью вопросительного знака <b>?</b>. 
Он позволяет создавать более гибкий функционал, который может работать с различными типами данных.</p>
<p>Существует три вида подстановочных знаков для разных целей:</p>
<ul>
<li><p><span class="b">Неограниченный Wildcard</span> (<code>?</code>)</p></li>
<li><p><span class="b">Wildcard, ограниченный "сверху"</span> (ограниченный базовым классом) (<code>? extends Type</code>)</p></li>
<li><p><span class="b">Wildcard, ограниченный "снизу"</span> (ограниченный производным классом) (<code>? super Type</code>)</p></li>
</ul>
<p>Рассмотрим эти типы подстановочных знаков и сценарии их использования на примере следующего класса Person:</p>
<pre class="brush:java;">
class Person&lt;T&gt;{

    private T id;
    private String name;

    T getId(){ return id; }
    void setId(T id){ this.id = id; }

    String getName() { return name; }

    Person(T id, String name){

        this.id = id;
        this.name = name;
    }
}
</pre>
<p>Тип Person является обобщенный и типизирован параметром <code>T</code>, который предоставляет тип для поля id.</p>

<p>Но прежде всего посмотрим на ситуацию, где подстановочные знаки могут помочь:</p>
<pre class="brush:java;">
public class Program{
       
    public static void main(String[] args) {
           
        Person&lt;Object&gt; bob = new Person&lt;&gt;(2.0, "Bob");
        Person&lt;Integer&gt; tom = new Person&lt;&gt;(1, "Tom");
        Person&lt;String&gt; sam = new Person&lt;&gt;("F-456", "Sam");

        printPersonInfo(bob);
        printPersonInfo(tom); // ! ОШибка:  tom - НЕ представляет тип Person&lt;Object&gt;
        printPersonInfo(sam); // ! ОШибка:  sam - НЕ представляет тип Person&lt;Object&gt;
    }

    static void printPersonInfo(Person&lt;Object&gt; person) {

        System.out.print("Name: " + person.getName());
        Object id = person.getId();
        System.out.println(";  Id: " + id);
    }
}
</pre>
<p>При попытке компиляции этой программы мы столкнемся с ошибками. Почему? Здесь метод <code>printPersonInfo()</code> в качестве параметра принимает объект типа <code>Person&lt;Object&gt;</code>. Типизация типом <code>Object</code> казалось бы охватит все возможные ситуации 
для поля id, в том числе когда это поле представляет типы <code>Integer</code> и <code>String</code> (как наследника класса <code>Object</code>). Однако в реальности мы сможем передать в этот метод объекты Person, 
которые типизирированы типами, отличными от <code>Object</code>:</p>
<pre class="brush:java;">
Person&lt;Integer&gt; tom = new Person&lt;&gt;(1, "Tom");
Person&lt;String&gt; sam = new Person&lt;&gt;("F-456", "Sam");

printPersonInfo(tom); // ! ОШибка:  tom - НЕ представляет тип Person&lt;Object&gt;
printPersonInfo(sam); // ! ОШибка:  sam - НЕ представляет тип Person&lt;Object&gt;
</pre>
<p>И подстановочные символы wildcard как раз позволяют решить эту проблему.</p>
<h3>Неограниченный Wildcard (?)</h3>
<p>Неограниченный wildcard (Unbounded Wildcard) используется, когда необходимо работать с обобщенным типом, где конкретный тип неизвестен или не важен. Такой подстановочный знак фактически обозначает "любой тип". 
Такой тип подстановочных знаков может быть полезен, когда логика вашего метода не зависит от конкретного типа, используемого в обобщении.</p>
<p>Рассмотрим следующий пример:</p>
<pre class="brush:java;">
public class Program{
       
    public static void main(String[] args) {
           
        // Пример использования:
        Person&lt;Integer&gt; tom = new Person&lt;&gt;(123, "Tom");
        Person&lt;String&gt; bob = new Person&lt;&gt;("A-456", "Bob");

        printPersonInfo(tom);   // Name: Tom;  Id: 123
        System.out.println();
        printPersonInfo(bob);   // Name: Bob;  Id: A-456
    }
    static void printPersonInfo(Person&lt;?&gt; person) {
        // Мы можем безопасно вызывать методы, не связанные с дженериком
        System.out.print("Name: " + person.getName());
        
        // Мы можем получить id, но компилятор будет рассматривать его как Object
        Object id = person.getId();
        System.out.println(";  Id: " + id);
    }
}
</pre>
<p>В данном случае определен метод <code>printPersonInfo</code>, который просто выводит информацию о человеке. Обратите внимание на тип его параметра:</p>
<pre class="brush:java;">Person&lt;?&gt; person</pre>
<p>То есть параметр <code>person</code> представляет класс Person, но каким типом типизирован этот класс, неважно. Поскольку здесь нам не важен тип его поля <code>id</code> - мы просто выводим его на консоль. В этом случае 
используется строковое представление поля id. Поэтому в этот метод мы можем передать объекты класса Person, типизированные различными типами, например, Integer или String:</p>
<pre class="brush:java;">
Person&lt;Integer&gt; tom = new Person&lt;&gt;(123, "Tom");
Person&lt;String&gt; bob = new Person&lt;&gt;("A-456", "Bob");

printPersonInfo(tom);   // Name: Tom;  Id: 123
printPersonInfo(bob);   // Name: Bob;  Id: A-456
</pre>
<p>Но поскольку компилятор здесь не знает, какой именно тип ожидает объект <code>Person&lt;?&gt;</code>, мы не можем выполнять ряд операций с полем id, например, установить его с помощью метода <code>setId()</code>:</p>
<pre class="brush:java;">
public class Program{
       
    public static void main(String[] args) {
           
        // Пример использования:
        Person&lt;Integer&gt; tom = new Person&lt;&gt;(123, "Tom");
        changePerson(tom, 25);
    }
    static void changePerson(Person&lt;?&gt; person, Object id) {

        person.setId(id); // ! ошибка
    }
}
</pre>
<p>Здесь при попытке установить id через вызов <code>person.setId(id)</code> мы полуим ошибку во время компиляции.</p>

