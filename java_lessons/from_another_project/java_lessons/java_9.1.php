	<p>Лямбда-выражения в языке Java представляют набор инструкций, 
которые можно выделить в отдельную переменную и затем многократно вызвать в различных местах программы.</p>
<h3>Определение лямбда-выражения и функциональные интерфейсы</h3>
<p>Для создания лямбда-выражения применяется <span class="b">лямбда-оператор</span> (стрелка <span class="b">-&gt;</span>). 
Этот оператор разделяет лямбда-выражение на две части:</p>
<pre class="brush:java;"> (параметры) -&gt; действия  </pre>
<p>левая часть (до стрелки) содержит параметры через запятую, а правая часть (после стрелки) собственно представляет выполняемые действия лямбда-выражения.</p>
<p>Лямбда-выражение не выполняется само по себе, а образует реализацию метода, определенного в <span class="b">функциональном интерфейсе</span>. Рассмотрим пример:</p>
<pre class="brush:java;">
public class Program {

    public static void main(String[] args) {
        
        Operationable op;
        op = (x,y)-&gt;x+y;
        
        int result = op.execute(10, 20);
        System.out.println(result); //30
    }   
}
interface Operationable{
    int execute(int x, int y);
}
</pre>
<p>Здесь в роли функционального интерфейса выступает интерфейс <code>Operationable</code>, в котором определен один метод без реализации - метод 
<code>execute</code>. Данный метод принимает два параметра - целых числа, и возвращает некоторое целое число.</p>

<p>Чтобы объявить и использовать лямбда-выражение, основная программа разбивается на ряд этапов:</p>
<ol>
<li><p>Определение ссылки на функциональный интерфейс:</p>
<pre class="brush:java;">Operationable op;</pre></li>
<li><p>Создание лямбда-выражения:</p>
<pre class="brush:java;">op = (x,y)-&gt;x+y;</pre>
<p>Причем параметры лямбда-выражения соответствуют параметрам единственного метода интерфейса Operationable, а результат соответствует возвращаемому результату 
метода интерфейса. При этом нам не надо использовать ключевое слово <code>return</code> для возврата результата из лямбда-выражения.</p>
<p>Так, в методе интерфейса оба параметра представляют тип <code>int</code>, значит, в теле лямбда-выражения мы можем применить к ним сложение. Результат сложения также представляет 
тип <code>int</code>, объект которого возвращается методом интерфейса.</p>
</li>
<li><p>Использование лямбда-выражения в виде вызова метода интерфейса:</p>
<pre class="brush:java;">int result = operation.execute(10, 20);</pre>
<p>Так как в лямбда-выражении определена операция сложения параметров, результатом метода будет сумма чисел 10 и 20.</p></li>
</ol>

<p>По факту лямбда-выражения являются в некотором роде сокращенной формой внутренних анонимных классов, которые ранее применялись в Java. В частности, 
предыдущий пример мы можем переписать следующим образом:</p>
<pre class="brush:java;">
public class Program {

    public static void main(String[] args) {
        
        Operationable op = new Operationable(){
        
            public int execute(int x, int y){
            
				return x + y;
            }
        };
         int z = op.execute(20, 10);
         System.out.println(z); // 30
    }   
}
interface Operationable{
    int execute(int x, int y);
}
</pre>
<p>При этом для одного функционального интерфейса мы можем определить множество лямбда-выражений. Например:</p>
<pre class="brush:java;">
Operationable sum = (int x, int y)-&gt; x + y;
Operationable sub = (int x, int y)-&gt; x - y;
Operationable mul = (int x, int y)-&gt; x * y;
        
System.out.println(sum.execute(20, 10)); //30
System.out.println(sub.execute(20, 10)); //10
System.out.println(mul.execute(20, 10)); //200
</pre>
<p>Если лямбда-выражение принимает один параметр, то скобки вокруг параметров можно не использовать:</p>
<pre class="brush:java;">
public class Program {

    public static void main(String[] args) {
        
        Printable printer = message -&gt; System.out.println(message);

        printer.print("Hello World");
        printer.print("Hello Work");
    }   
}
interface Printable{
    void print(String message);
}
</pre>
<p>Здесь лямбда-выражение printer представляет функциональный интерфейс Printable, единственный метод которого - print принимает только один параметр.</p>
<p>Другая ситуация - в методе функционального интерфейса есть параметр, но в лямбда-выражении он не используется. В этом случае вместо параметра можно указать прочерк:</p>
<pre class="brush:java;">
public class Program {

    public static void main(String[] args) {
        
        Printable printer = _ -&gt; System.out.println("Test");

        // при вызове параметру все равно надо передать значение
        // но оно не имеет значения, так как не будет использоваться
        printer.print(null);    // Test
        printer.print("brr");   // Test
    }   
}
interface Printable{
    void print(String message);
}
</pre>
<p>Если метод интерфейса вообще не принимает никаких параметров, то при определении лямбда-выражения указываются пустые скобки:</p>
<pre class="brush:java;">
public class Program {

    public static void main(String[] args) {
        
        Hello speaker = () -&gt; System.out.println("Привед");

        speaker.sayHello();
    }   
}
interface Hello{
    void sayHello();
}
</pre>
<h3>Отложенное выполнение</h3>
<p>Одним из ключевых моментов в использовании лямбд является <span class="b">отложенное выполнение</span> (deferred execution). То есть мы определяем в одном месте программы 
лямбда-выражение и затем можем его вызывать при необходимости неопределенное количество раз в различных частях программы. Отложенное выполнение может потребоваться, к примеру, в следующих случаях:</p>
<ul>
<li><p>Выполнение кода отдельном потоке</p></li>
<li><p>Выполнение одного и того же кода несколько раз</p></li>
<li><p>Выполнение кода в результате какого-то события</p></li>
<li><p>Выполнение кода только в том случае, когда он действительно необходим и если он необходим</p></li>
</ul>

