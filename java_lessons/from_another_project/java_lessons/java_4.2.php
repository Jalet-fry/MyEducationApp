<h3>Обработка нескольких исключений</h3>
<p>В одной и той же программе на одном и том же участке кода может возникать несколько разных типов исключений. Обрабатывая исключения типа <code>Throwable</code> или <code>Exception</code>, 
мы можем покрыть все эти типы исключений. Но Java также позволяет разграничить обработку различных видов исключений, добавив дополнительные блоки <code>catch</code> для каждого обрабатываемого типа исключения:</p>
<pre class="brush:java;">
class Program{
     
	public static void main(String[] args) {
         
        printNumber(0);     // По индексу 0 число 1
        printNumber(10);    // Выход за пределы массива
        printNumber(3);     // Ошибка преобразования из строки в число
    }

    static void printNumber(int index){

        String[] data = {"1", "a", "2", "b", "3", "c"};

        try{
            // пытаемся преобразовать значение массива по индексу в число
            int result =Integer.parseInt(data[index]);
            System.out.printf("По индексу %d число %d\n", index, result);
        }
        catch(ArrayIndexOutOfBoundsException _){
                    
            System.out.println("Выход за пределы массива");
        }
        catch(NumberFormatException _){
                    
            System.out.println("Ошибка преобразования из строки в число");
        }
    }
}
</pre>
<p>В данном случае основные действия разворачиваются в методе <code>printNumber()</code>. Этот метод получает извне индекс и пытается преобразовать значение из массива по этому индексу в число. 
И в этом случае у нас может быть несколько вариантов развития ситуации:</p>
<ol>
<li><p>По переданному индексу в массиве располагается число (только в виде строки), тогда преобразование завершается успешно</p></li>
<li><p>Переданный индекс находится вне допустимого диапазона, тогда мы столкнемся с исключением типа <code>ArrayIndexOutOfBoundsException</code></p></li>
<li><p>Переданный индекс действителен, но значение по нему невозможно преобразовать в число. Тогда мы столкнемся с исключением типа <code>NumberFormatException</code></p></li>
</ol>
<p>Для отслеживания последних двух ситуаций в конструкции <code>try..catch</code> определено два блока <code>catch</code>:</p>
<pre class="brush:java;">
catch(ArrayIndexOutOfBoundsException _){
                    
    System.out.println("Выход за пределы массива");
}
catch(NumberFormatException _){
                    
    System.out.println("Ошибка преобразования из строки в число");
}
</pre>
<p>Если у нас возникает исключение определенного типа, то оно переходит к соответствующему блоку <code>catch</code>.</p>
<p>Подобная стратегия позволяет разграничить обработку различных типов исключений. Однако, что, если у нас в коде может возникнуть большее количество исключений - не создавать же на каждый тип исключений из стандартной 
библиотеки Java свой блок <code>catch</code>! В этом случае мы можем определить ряд блоков <code>catch</code> для тех типов, для которых мы хотим определить специальную обработку. А для всех остальных типов 
исключений определить блок <code>catch</code> с обработкой более общего типа как <code>Throwable</code> или <code>Exception</code>. Например:</p>
<pre class="brush:java;">
class Program{
     
	public static void main(String[] args) {
         
        printNumber(0);     // По индексу 0 число 1
        printNumber(10);    // Выход за пределы массива
        printNumber(3);     // For input string: "b"
    }

    static void printNumber(int index){

        String[] data = {"1", "a", "2", "b", "3", "c"};

        try{
            // пытаемся преобразовать значение массива по индексу в число
            int result =Integer.parseInt(data[index]);
            System.out.printf("По индексу %d число %d\n", index, result);
        }
        catch(ArrayIndexOutOfBoundsException _){  // обрабатываем выход за границы массива
                    
            System.out.println("Выход за пределы массива");
        }
        catch(Exception ex){        // обрабатываем все остальные типы исключений
                    
            System.out.println(ex.getMessage());    // выводим сообщение об исключении
            ex.printStackTrace();
        }
    }
}
</pre>
<p>В данном случае отдельно обрабатываем исключение типа <code>ArrayIndexOutOfBoundsException</code>, то есть выход за границы массива. А для других типов обрабатываем исключения типа <code>Exception</code></p>
<p>При этом стоит учитывать, что блоки <code>catch</code> для обработки более конкретных (производных) типов (как <code>ArrayIndexOutOfBoundsException</code>) должны располагаться сначала, а блоки
<code>catch</code> для обработки более общих (базовых) типов (как <code>Exception</code> или <code>Throwable</code>) - в конце, как в примере выше.</p>
	

