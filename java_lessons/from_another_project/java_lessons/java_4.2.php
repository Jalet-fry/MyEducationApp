	<h3>Класс Throwable</h3>
<p>Базовым классом для всех исключений в языке Java является класс <span class="b">Throwable</span>. Поэтому, если мы хотим обработать в блоке <code>catch</code> все возможные исключения, то мы можем использовать этот тип.</p>
<p>Данный класс определяет ряд базовых методов, отмечу основные из них:</p>
<ul>
<li><p><code>String getMessage()</code>: возвращает строку подробного сообщения об исключении</p></li>
<li><p><code>StackTraceElement[] getStackTrace()</code>: возвращает информацию о трассировке стека, выведенной функцией printStackTrace()</p></li>
<li><p><code>void printStackTrace()</code>: выводит трассировку стека в стандартный поток ошибок</p></li>
</ul>
<p>Используем эти методы для получения информации об исключении при его обработке:</p>
<pre class="brush:java;">
class Program{
     
	public static void main(String[] args) {
         
        try{
            // для эмуляции ошибки делим число на 0
            System.out.println(5 / 0);
        }
        catch(Throwable ex){

            // выводим сообщение об ошибке
            System.out.println("Error: " + ex.getMessage());
            // выводим трасировку стека
            ex.printStackTrace();
        }
    }
}
</pre>
<p>Здесь для генерации исключения в блоке <code>try</code> делим число на 0. А в блоке <code>catch</code> объявляем переменную <code>ex</code>, которая представляет тип <code>Throwable</code> и выводим на консоль 
по отдельности сообщение об ошибке и трассировку стека (которая также включает сообщение об ошибке). В итоге мы получим следующий консольный вывод:</p>
<pre class="sh">
Error: / by zero
java.lang.ArithmeticException: / by zero
	at Program.main(Program.java:7)
</pre>
<p>Трассировка стека позволяет более детально узнать, какой реально тип ошибки, где произвошла ошибка. Так, из выведенной информации мы видим, что в реальности исключение представляет тип 
<code>java.lang.ArithmeticException</code> (то есть тип исключений для арифметических операций). А сама ошибка возникла на 7 строке файла <code>Program.java</code> в методе <code>Program.main</code></p>

<h3>Классификация ошибок</h3>
<p>От класса <code>Throwable</code> наследуются два других класса: <span class="b">Error</span> 
и <span class="b">Exception</span>. Все остальные классы являются производными от этих двух классов.</p>

<p>Класс <b>Error</b> описывает внутренние ошибки в исполняющей среде Java. Программист имеет очень ограниченные возможности для обработки подобных ошибок. 
При возникновении такой ошибки мало что можно сделать, кроме как уведомить пользователя и попытаться корректно завершить программу. Такие ситуации встречаются довольно редко.</p>

<p>Собственно исключения наследуются от класса <b>Exception</b>. Среди этих исключений следует выделить класс <span class="b">RuntimeException</span>. Все классы исключений, которые унаследованы от классов 
<code>Error</code> и <code>RuntimeException</code> еще называются <span class="b">непроверяемыми исключениями</span> (unchecked exceptions) - 
компилятор не проверяет факт обработки таких исключений. 
Такие исключения нередко являются следствием ошибок разработчика, например, неверное преобразование типов или выход за пределы массива.</p>
<p>Некоторые из классов непроверяемых исключений:</p>
<ul>
<li><p><span class="b">ArithmeticException</span>: исключение, возникающее при делении на ноль</p></li>
<li><p><span class="b">IndexOutOfBoundException</span>: индекс вне границ массива</p></li>
<li><p><span class="b">IllegalArgumentException</span>: использование неверного аргумента при вызове метода</p></li>
<li><p><span class="b">NullPointerException</span>: использование пустой ссылки</p></li>
<li><p><span class="b">NumberFormatException</span>: ошибка преобразования строки в число</p></li>
</ul>
<p>Все остальные классы, образованные от класса <code>Exception</code>, называются проверяемыми исключениями (checked exceptions).</p>
<p>Некоторые из классов проверяемых исключений:</p>
<ul>
<li><p><span class="b">CloneNotSupportedException</span>: класс, для объекта которого вызывается клонирование, не реализует интерфейс Cloneable</p></li>
<li><p><span class="b">InterruptedException</span>: поток прерван другим потоком</p></li>
<li><p><span class="b">ClassNotFoundException</span>: невозможно найти класс</p></li>
</ul>
<p>В итоге получается примерно следующая иерархия исключений:</p>
<img src="./pics/4.1.png" alt="Иерархия классов исключений в Java" />
<p>Таким образом, вместо исключения общего типа <code>Throwable</code> мы можем обрабатывать конкретные типы исключений. 
Например, при делении на 0 генерируется исключение типа <code>ArithmeticException</code>. Обработаем его:</p>
<pre class="brush:java;">
class Program{
     
	public static void main(String[] args) {
         
        try{
            // для эмуляции ошибки делим число на 0
            System.out.println(5 / 0);
